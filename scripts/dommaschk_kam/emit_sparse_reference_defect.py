END = 'end PlasmaLean.Design.DommaschkReferenceFirst\n'


def check_abs(residual, budget):
    """The exact lower Horner bound used by QPoly.checkOn on eight subintervals."""
    for index in range(8):
        left = Fraction(index, 4) - 1
        for sign in (1, -1):
            shifted = [sign * sum(comb(k, j) * left**(k-j) * residual.a[k]
                                  for k in range(j, len(residual.a)))
                       for j in range(len(residual.a))]
            lower = 0
            for a in reversed(shifted):
                lower = a + min(0, Fraction(lower, 4))
            if residual.e - lower > budget*SCALE:
                raise ArithmeticError('subinterval fails the proposed defect bound')


def emit():
    u, z, cosine, sine = inputs()
    columns = (Model(u.a, 0), Model(z.a, 0), cosine, sine)
    files = {}
    input_header = HEADER + 'public import PlasmaLean.Design.DommaschkBounceTaylorFirstInputs\n' + COMMON
    files[STEM+'Inputs'] = (input_header +
        '/-- Dyadic central polynomial, with both harmonic errors retained. -/\n'
        'def reference : Inputs := ⟨' + ',\n  '.join(model_literal(m) for m in columns) +
        '⟩\n\n' + END)
    values = {}
    for name, suffix in [('dD','D'),('dnR','R'),('dnZ','Z')]:
        text = field(name, columns, input_name='reference')
        files[STEM+suffix] = (HEADER + 'public import PlasmaLean.Design.' + STEM + 'Inputs\n' +
                              COMMON + text + '\n' + END)
        values[name] = sum(models(coefficients(DATA.read_text(), name), columns), ZERO)
    imports = ['public import PlasmaLean.Design.'+STEM+s+'\n' for s in ('D','R','Z')]
    out = HEADER + ''.join(imports) + 'public import PlasmaLean.Design.DommaschkTaylorResidual\n' + COMMON
    for name, n, position, m, b in [('radial','dnR','u',columns[0],10**12),
                                    ('vertical','dnZ','z',columns[1],10**13)]:
        slope = Model([128*(j+1)*value for j, value in enumerate(m.a[1:])])
        residual = values[n] - slope*values['dD']
        check_abs(residual, Fraction(1,b))
        out += (f'/-- Signed numerator after cancellation of reference slope times denominator. -/\n'
                f'def {name}Residual : Model := {model_literal(residual)}\n\n'
                f'theorem {name}_match : Matches (TaylorResidual.numerator ⟨7,80⟩ 128 '
                f'{n}0 dD0 reference.{position}) {name}Residual := by\n'
                '  constructor <;> apply eq_of_beq <;> kernel_fact\n\n'
                f'theorem {name}_bound {{s y : ℝ}} (hs : |s| ≤ 1) (h : {name}Residual.Mem s y) :\n'
                f'    |y| ≤ 1 / {b} := by\n'
                f'  have bound := TaylorResidual.abs_bound (q := 1 / {b})\n'
                '    (pts := [-3/4,-1/2,-1/4,0,1/4,1/2,3/4,1]) hs h (by kernel_fact) (by kernel_fact)\n'
                '  simpa only [Rat.cast_div, Rat.cast_one, Rat.cast_ofNat] using bound\n\n')
    with gzip.open(RECORD, 'rt') as fp:
        rec = json.load(fp)
    row, = [t['steps'][0] for t in rec['traces'] if t['direction'] == 1]
    frame = row['frame_end']
    out += ('/-- Exact endpoint of the first forward moving frame. -/\n'
            'def frameEnd : Fin 2 → Fin 2 → ℚ :=\n  ![' +
            ', '.join('!['+', '.join(f'{v} / {rec["frame_denominator"]}' for v in a)+']'
                      for a in frame) + ']\n\n/-- Submitted upper defect in the moving frame. -/\n'
            f'def recordedDefect : ℚ := {row["defect_upper"]}\n\n')
    files[STEM+'DefectData'] = out + END
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in emit().items():
        path = DEST / (name+'.lean')
        if args.check:
            if path.read_text() != text:
                raise SystemExit('regenerate ' + path.name)
        else:
            path.write_text(text)
