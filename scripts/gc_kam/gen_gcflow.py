def lean_rat(r):
    r = sp.Rational(r)
    if r.q == 1: return '(%d)' % r.p
    return '(%d/%d)' % (r.p, r.q)

def wrap(text, indent=4, width=98):
    """Break a long Lean line at top-level-ish ` + `, ` - `, ` = `, ` * ` boundaries."""
    out, cur = [], ''
    text = text.replace(' := by linear_combination ', ' :=\x01by\x01linear_combination\x01')
    text = text.replace(' at ', ' at\x01').replace('(%d) * ' % 1, '(1)\x01*\x01')
    toks = text.split(' ')
    for t in toks:
        cand = (cur + ' ' + t) if cur else t
        if len(cand) + (indent if out else 4) > width and cur and not cur.endswith(
                ('linear_combination', ' by', ':=', '(%d)' % 1)) and cur.split(' ')[-1] not in (
                'linear_combination', 'by', ':='):
            out.append(cur)
            cur = t
        else:
            cur = cand
    out.append(cur)
    return ('\n' + ' ' * indent).join(out).replace('\x01', ' ')

def wrap_doc(text, width=100):
    lines = []
    for para in text.split('\n'):
        cur = ''
        for w in para.split(' '):
            cand = (cur + ' ' + w) if cur else w
            if len(cand) > width and cur:
                lines.append(cur); cur = w
            else:
                cur = cand
        lines.append(cur)
    return '\n'.join(lines)

def emit_poly_scaled(name, expr, doc, scale):
    """`name = (1/scale) * (integer polynomial)`."""
    P = sp.Poly(sp.expand(expr * scale), u, z, c, s)
    terms = sorted(P.terms(), key=lambda t: (-sum(t[0]), t[0]))
    lines = []
    for (i, j, k, l), co in terms:
        assert sp.Rational(co).q == 1
        mono = ['(%d, %d)' % (idx, e) for idx, e in enumerate((i, j, k, l)) if e]
        lines.append('    monoE (%d) [%s]' % (int(co), ', '.join(mono)))
    return ('/-- %s -/\ndef %s : PolyExpr ℂ (Fin 6) := mul (const (1 / %d)) (sumE [\n%s])\n'
            % (doc, name, scale, ',\n'.join(lines)))

def emit_poly(name, expr, doc):
    if name == 'EpP':
        return emit_poly_scaled(name, expr, doc, 256)
    P = sp.Poly(expr, u, z, c, s)
    terms = sorted(P.terms(), key=lambda t: (-sum(t[0]), t[0]), reverse=False)
    lines = []
    for (i, j, k, l), co in terms:
        mono = []
        for idx, e in enumerate((i, j, k, l)):
            if e: mono.append('(%d, %d)' % (idx, e))
        lines.append('    monoE %s [%s]' % (lean_rat(co), ', '.join(mono)))
    return '/-- %s -/\ndef %s : PolyExpr ℂ (Fin 6) := sumE [\n%s]\n' % (doc, name, ',\n'.join(lines))

