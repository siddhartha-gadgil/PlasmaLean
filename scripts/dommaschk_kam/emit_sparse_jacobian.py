def derivative(terms, axis):
    out = []
    for q, exps in terms:
        if exps[axis]:
            powers = list(exps)
            powers[axis] -= 1
            out.append((q * exps[axis], powers))
    return out


def derivative_file(source, name, axis, blocks, namespace=PREFIX, inputs_module="DommaschkBounceTaylorFirstInputs", context="DommaschkBounceTaylorFirst"):
    variable = ['dU', 'dZ'][axis]
    out = header([inputs_module], 'First forward trial-tube spatial derivative' if namespace == PREFIX else 'Full trial-tube spatial derivative', namespace, context)
    out += f'abbrev {name} := {variable} {source}\n\n'
    total = ZERO
    suffix = '(constant 0)'
    for j in reversed(range(len(blocks))):
        start = j * BLOCK
        tag = f'{name}{start}'
        head = blocks[j]
        total = head + total
        out += f'''def {tag} : Model := {model_literal(total)}

private theorem {tag}_checked : Blocks {FORMAT} trial ({name}.drop {start}) {tag} := by
  apply Blocks.chunk {BLOCK} ({model_literal(head)}) {suffix}
  · constructor <;> apply eq_of_beq <;> kernel_fact
  · exact {suffix + '_checked' if j < len(blocks)-1 else 'Blocks.nil'}
  · constructor <;> apply eq_of_beq <;> kernel_fact

'''
        suffix = tag
    out += f'''/-- The derivative enclosure covers the full trial tube at every normalized time. -/
theorem {name}_checked : Blocks {FORMAT} trial {name} {name}0 := {name}0_checked

'''
    return out + f'end PlasmaLean.Design.{namespace}\n'


def matrix_certificate(source_models, step, *, namespace=PREFIX, start=None, dependencies=None,
                       context="DommaschkBounceTaylorFirst", numeric=None):
    from bounce_phase_frame import FRAME_SCALE, affine_frame

    columns = ['DU', 'DZ', 'RU', 'RZ', 'ZU', 'ZZ']
    imports = ['DommaschkJacobianFrames', 'DommaschkBounceTaylorFirst'] + [PREFIX + x for x in columns]
    title = ('Checked trace and traceless parts of the first forward spatial Jacobian'
             if namespace == PREFIX else 'Checked trace and traceless parts of the spatial Jacobian')
    out = header(imports if dependencies is None else dependencies, title, namespace, context)
    out += 'open PlasmaLean.Certificates.PositionFrameSlabs\n\n'
    if start is None:
        start = [[FRAME_SCALE,0],[0,FRAME_SCALE]]
    end = step['frame_end']
    m, dm, _, _, _ = affine_frame(start,end,F(1,64))
    flatten = lambda mat: [x for row in mat for x in row]
    out += 'def firstLeft : Frame := ⟨' + ', '.join(map(str,flatten(start))) + '⟩\n'
    out += 'def firstRight : Frame := ⟨' + ', '.join(map(str,flatten(end))) + '⟩\n\n'
    defs, proof = [], []
    table = {}
    for k,(mname, poly, model) in source_models.items():
        proof.append(f'  have h{k} := {poly}_checked.mem ht hin')
        table[k] = (mname, model)
    for tag, dat, val in [('M',m,'frameEntries firstLeft firstRight t'),
                          ('V',dm,'velocityEntries firstLeft firstRight')]:
        for k, model in zip('abcd',flatten(dat)):
            name = tag+k
            md = 'model'+name
            defs.append(f'private def {md} : Model := {model_literal(model)}')
            defs.append(f'''private theorem leaf{name} (t : ℝ) : {md}.Mem t (({val}).{k}) := by
  rw [show {md} = {model_literal(model)} by rfl, mem_ofDyadic_iff]
  norm_num [frameEntries, velocityEntries, firstLeft, firstRight, entry, Entries.sub, Entries.scale,
    PlasmaLean.Certificates.QPoly.eval_cons, PlasmaLean.Certificates.QPoly.eval_nil,
    abs_nonpos_iff]{chr(10)+'  ring' if tag == 'M' else ''}
''')
            proof.append(f'  have h{name} := leaf{name} t')
            table[name] = md, model
    def binary(name, op, x, y):
        ax, a = table[x]
        by, b = table[y]
        model = {'add':add, 'mul':lambda a,b:a*b, 'sub':lambda a,b:a-b}[op](a,b)
        md = 'model'+name
        defs.append(f'private def {md} : Model := {model_literal(model)}')
        defs.append(f'''private theorem check{name} : Matches (format.{op} {ax} {by}) {md} := by
  constructor <;> apply eq_of_beq <;> kernel_fact
''')
        proof.append(f'  have h{name} := (check{name}.eq ▸ format.{op}_mem ht h{x} h{y})')
        table[name] = md,model
        return name
    def neg(name,x):
        ax,a=table[x]
        md='model'+name
        defs.append(f'private def {md} : Model := {model_literal(-a)}')
        defs.append(f'''private theorem check{name} : Matches (format.neg {ax}) {md} := by
  constructor <;> apply eq_of_beq <;> kernel_fact
''')
        proof.append(f'  have h{name} := (check{name}.eq ▸ format.neg_mem ht h{x})')
        table[name] = md,-a
        return name
    den2 = binary('denSq','mul','D','D')
    jac = [[binary(f'J{i}{j}','sub',binary(f'N{i}{j}','mul',g,'D'),
                   binary(f'D{i}{j}','mul',n,d)) for j,(g,d) in enumerate(zip(gs,['DU','DZ']))]
           for i,(n,gs) in enumerate([('R',['RU','RZ']),('Z',['ZU','ZZ'])])]
    M = [['Ma','Mb'],['Mc','Md']]
    V = [['Va','Vb'],['Vc','Vd']]
    def product(tag,X,Y):
        return [[binary(f'{tag}{i}{j}','add',*[
            binary(f'{tag}{i}{j}k{k}','mul',X[i][k],Y[k][j]) for k in (0,1)]) for j in (0,1)] for i in (0,1)]
    jm = product('jm',jac,M)
    center = [[binary(f'center{i}{j}','sub',jm[i][j],binary(f'rate{i}{j}','mul',den2,V[i][j]))
               for j in (0,1)] for i in (0,1)]
    A = product('num', [[M[1][1],neg('negB','Mb')],[neg('negC','Mc'),M[0][0]]],center)
    det = binary('det','sub',binary('detAD','mul','Ma','Md'),binary('detBC','mul','Mb','Mc'))
    denom = binary('den','mul',det,den2)
    t = binary('tr','add',A[0][0],A[1][1])
    v = binary('dif','sub',A[0][0],A[1][1])
    w = binary('off','add',A[0][1],A[1][0])
    bounds = ['10173/10000','3/10000','1017/1000','943/1000000','39764/1000000','2884/1000000']
    if numeric is not None:
        bounds = numeric(table,step)
    mid,dr,dl,tr,di,off = bounds
    for k,mid,rad in [(denom,mid,dr),(t,'0',tr),(v,'0',di),(w,'0',off)]:
        md,_ = table[k]
        defs.append(f'''private theorem range{k} {{t y : ℝ}} (ht : |t| ≤ 1) (h : {md}.Mem t y) :
    |y - {mid}| ≤ {rad} := by
  have hh := enclose (c := ⟨[{mid}], {rad}⟩) ht h (by kernel_fact)
  simpa [Model.Mem, PlasmaLean.Certificates.QPoly.eval_cons,
    PlasmaLean.Certificates.QPoly.eval_nil] using hh
''')
        proof.append(f'  have bound{k} := range{k} ht h{k}')
    out += '\n'.join(defs)
    params = dict(zip(('mid','dr','dl','tr','di','off'), bounds, strict=True))
    params['scope'] = 'first-forward' if namespace == PREFIX else 'forward'
    out += Template('''
/-- Joint bounds on the full $scope trial tube. All matrix and field
factors use the same normalized time and the same physical point. -/
theorem symmetric_bounds {t u z c s : ℝ} (ht : |t| ≤ 1) (hin : trial.Mem t u z c s) :
    let m := frameEntries firstLeft firstRight t
    let denSq := evR u z c s dD * evR u z c s dD
    let A := transformedNumerator (spatialNumerator u z c s) m
      (velocityEntries firstLeft firstRight) denSq
    $dl ≤ m.det * denSq ∧ A.a + A.d ≤ $tr ∧
      |A.a-A.d| ≤ $di ∧ |A.b+A.c| ≤ $off := by
''').substitute(params)
    out += '\n'.join(proof)
    out += Template('''
  have lower (v : ℝ) (h : |v - $mid| ≤ $dr) : $dl ≤ v := by
    linarith only [(abs_le.mp h).1]
  dsimp only [transformedNumerator, spatialNumerator, quotientNumerator,
    Entries.product, Entries.adj, Entries.sub, Entries.scale, Entries.det]
  refine ⟨lower _ boundden, ?_, ?_, ?_⟩
  · exact (le_abs_self _).trans (by simpa only [sub_zero] using boundtr)
  · exact (by simpa only [sub_zero] using bounddif)
  · exact (by simpa only [sub_zero] using boundoff)

''').substitute(params)
    return out + f'end PlasmaLean.Design.{namespace}\n'


def emit():
    columns = inputs()
    files = {}
    source_models = {}
    source_text = DATA.read_text()
    for source, tag in [('dD','D'),('dnR','R'),('dnZ','Z')]:
        terms = coefficients(source_text, source)
        source_models[tag] = source+'0', source, reduce(add, models(terms, columns), ZERO)
        for axis, variable in enumerate('UZ'):
            name = 'grad' + tag + variable
            blocks = models(derivative(terms, axis), columns)
            files[PREFIX + tag + variable] = derivative_file(source, name, axis, blocks)
            source_models[tag+variable] = name+'0', name, reduce(add,blocks,ZERO)
    with gzip.open(RECORD, 'rt') as handle:
        packet = json.load(handle)
    trace, = (t for t in packet['traces'] if t['direction'] == 1)
    files[PREFIX+'First'] = matrix_certificate(source_models,trace['steps'][0])
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--forward',type=int,metavar='INDEX',
                        help='emit the general forward certificate at this zero-based slab')
    args = parser.parse_args()
    if args.forward is None:
        files = emit()
    else:
        if not 0 <= args.forward < 391:
            parser.error('INDEX must be between 0 and 390')
        from emit_sparse_forward_jacobian import emit as forward
        files = forward(args.forward)
    for name, text in files.items():
        path = DEST / (name + '.lean')
        if args.check:
            if path.read_text() != text:
                raise SystemExit('regenerate ' + str(path))
        else:
            path.write_text(text)
