"""Assemble the per-slab wide-tube certificates of one group into a single chain.

`wide_tube_pilot.py` proves, for every slab k of a group, `checked` (the wide step check from
the state left by slab k-1) and `field_bounds`. Its own chain module states all slabs in one
proof, which does not scale beyond a few dozen slabs. This script writes
`WideTube/<Group>Joined.lean`: chains over chunks of 8 slabs, composed with
`PositionFrameWideChain.Steps.append` and `fieldBoundsOn_append`, and the trajectory theorem
for the whole group. It then compiles the module and records `#print axioms`.

    .venv-ws/bin/python scripts/qa2r_wide/assemble_chain.py --root .lake/qa2r-wide/forward --count 332
"""
import argparse
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ALLOWED = "[propext, Classical.choice, Quot.sound]"


def source(group, first, count, chunk):
    name = group + "Joined"
    imports = "".join(f"public import WideTube.DommaschkWideTubeF{first + k:03}\n" for k in range(count))
    parts, pieces = [], []
    for j, lo in enumerate(range(0, count, chunk)):
        ks = list(range(lo, min(lo + chunk, count)))
        start = f"{group}.start" if lo == 0 else f"(next {group}.row{lo - 1})"
        stop = f"(next {group}.row{ks[-1]})"
        rows = ", ".join(f"{group}.row{k}" for k in ks)
        checked = ", ".join(f"DommaschkWideTubeF{first + k:03}.checked" for k in ks)
        bounds = []
        for i, k in enumerate(ks):
            clock = f"({first + lo} / 64 : ℝ)" + " + 1 / 64" * i
            head = f"  · rw [show {clock} = {first + k} / 64 by norm_num]\n    " if i else "  · "
            bounds.append(head + f"exact DommaschkWideTubeF{first + k:03}.field_bounds")
        parts.append(f"""
def rows{j} : List Step := [{rows}]

theorem steps{j} : Steps {start} rows{j} {stop} := ⟨{checked}, rfl⟩

theorem bounds{j} : FieldBoundsOn (euclideanFlow 0 1) (velocityJacobian 0 1) {start}
    ({first + lo} / 64) rows{j} ballDomain := by
  refine ⟨{', '.join(['?_'] * len(ks))}, trivial⟩
{chr(10).join(bounds)}
""")
        done = ks[-1] + 1
        if j == 0:
            parts.append(f"""
def all0 : List Step := rows0

theorem length0 : all0.length = {done} := rfl

theorem stepsTo0 : Steps {group}.start all0 {stop} := steps0

theorem boundsTo0 : FieldBoundsOn (euclideanFlow 0 1) (velocityJacobian 0 1) {group}.start
    ({first} / 64) all0 ballDomain := bounds0
""")
        else:
            parts.append(f"""
def all{j} : List Step := all{j - 1} ++ rows{j}

theorem length{j} : all{j}.length = {done} := by
  rw [all{j}, List.length_append, length{j - 1}]
  rfl

theorem stepsTo{j} : Steps {group}.start all{j} {stop} := stepsTo{j - 1}.append steps{j}

theorem boundsTo{j} : FieldBoundsOn (euclideanFlow 0 1) (velocityJacobian 0 1) {group}.start
    ({first} / 64) all{j} ballDomain :=
  fieldBoundsOn_append stepsTo{j - 1} boundsTo{j - 1}
    (by rw [length{j - 1}]; norm_num) bounds{j}
""")
        pieces.append(j)
    last = pieces[-1]
    final = f"(next {group}.row{count - 1})"
    return name, f"""/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

{imports}
/-! # One chain through forward slabs {first}–{first + count - 1} of the wide tube, label 0.474

Generated by `scripts/qa2r_wide/assemble_chain.py`. -/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{name}

open Certificates PositionFrameSlabs PositionFrameWideChain DommaschkJacobian Set

set_option linter.style.longLine false
{''.join(parts)}
/-- All records in order of increasing angle. -/
abbrev rows : List Step := all{last}

/-- State left by the last record. -/
abbrev exitState : State := {final}

theorem steps : Steps {group}.start rows exitState := stepsTo{last}

theorem field_bounds : FieldBoundsOn (euclideanFlow 0 1) (velocityJacobian 0 1) {group}.start
    ({first} / 64) rows ballDomain := boundsTo{last}

/-- Every point of the entrance ellipsoid launches one field line through all {count} slabs,
ending in the exit ellipsoid and lying in every recorded tube. -/
theorem trajectory {{x : Plane}} (entry : x ∈ stateSet {group}.start) :
    ∃ v : ℝ → Plane, v ({first} / 64) = x ∧ v ({first} / 64 + {count} / 64) ∈ stateSet exitState ∧
      (∀ t ∈ Icc ({first} / 64 : ℝ) ({first} / 64 + {count} / 64),
        HasDerivWithinAt v (euclideanFlow 0 1 t (v t))
          (Icc ({first} / 64 : ℝ) ({first} / 64 + {count} / 64)) t) ∧
      ∀ slab ∈ physicalSlabs {group}.start ({first} / 64) rows,
        ∀ t ∈ Icc slab.start slab.stop, v t ∈ slab.tube t := by
  have h := steps.trajectory_of_length (n := {count}) length{last} field_bounds entry
  exact_mod_cast h

end PlasmaLean.Design.{name}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--group", default="DommaschkWideTubeRows000")
    parser.add_argument("--first", type=int, default=0)
    parser.add_argument("--count", type=int, required=True)
    parser.add_argument("--chunk", type=int, default=8)
    args = parser.parse_args()
    root = (ROOT / args.root).resolve()
    name, text = source(args.group, args.first, args.count, args.chunk)
    tree = root / "WideTube"
    (tree / (name + ".lean")).write_text(text)
    lake = lambda *a: subprocess.check_output(["lake", "env", *a], cwd=ROOT, text=True).strip()
    lean = str(Path(lake("lean", "--print-prefix")) / "bin/lean")
    env = {**os.environ, "LEAN_PATH": os.pathsep.join([str(root), lake("printenv", "LEAN_PATH")])}
    build = subprocess.run([lean, "-j1", "-DwarningAsError=true", "-R", str(root), "-o",
                            str(tree / (name + ".olean")), str(tree / (name + ".lean"))],
                           env=env, capture_output=True, text=True)
    if build.returncode:
        raise SystemExit(build.stdout[-3000:] + build.stderr[-3000:])
    audit = root / "AuditJoined.lean"
    claims = [f"PlasmaLean.Design.{name}.{t}" for t in ("steps", "field_bounds", "trajectory")]
    audit.write_text(f"import WideTube.{name}\n" + "".join(f"#print axioms {c}\n" for c in claims))
    out = subprocess.run([lean, "-j1", "-R", str(root), str(audit)], env=env, capture_output=True, text=True)
    log = out.stdout + out.stderr
    (root / "audit-joined.log").write_text(log)
    for c in claims:
        if f"'{c}' depends on axioms: {ALLOWED}" not in " ".join(log.split()):
            raise SystemExit("axiom audit failed for " + c + "\n" + log[-2000:])
    print(name, "compiled;", len(claims), "theorems on standard axioms")


if __name__ == "__main__":
    main()
