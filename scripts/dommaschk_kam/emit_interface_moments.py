"""Regenerate (or --check) the signed and absolute integer moments of the interface jets."""
import argparse
from pathlib import Path

from emit_interface_columns import columns
from interface_arc import DATA

OUTPUT = DATA.with_name('DommaschkKamAInterfaceMomentData.lean')


def moment_rows():
    full = columns()
    rows = []
    for height in (False, True):
        for a in range(3):
            for b in range(3-a):
                c = [row[3*height+a] * (2*m)**b for m,row in zip(range(-80,81),full)]
                phase = a+b-height
                signed = [sum(value * (2*m)**d for m,value in zip(range(-80,81), c))
                          * (1,0,-1,0)[(phase+d)%4] for d in range(5)]
                fifth = sum(abs(value) * abs(2*m)**5 for m,value in zip(range(-80,81),c))
                rows.append((str(height).lower(),a,b,signed,fifth))
    return rows


def emit():
    rows = moment_rows()
    s = '''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import Mathlib.Data.Int.Basic

/-!
# Integer moments of the degree-four torus-A interface enclosure

Generated by `scripts/dommaschk_kam/emit_interface_moments.py` from the full signed Fourier
grid. The denominator shared by all moments is 2^128. The radial profile uses the offset
29/32 separately. The last column is an absolute fifth moment for the Taylor remainder.
-/

@[expose] public section

namespace PlasmaLean.Design.DommaschkKamAInterfaceMoments

set_option linter.style.longLine false in
/-- The five signed Taylor numerators, including the initial phase of the jet. -/
def momentRow : Bool → ℕ → ℕ → List ℤ
'''
    for height,a,b,signed,_ in rows:
        s += f'  | {height}, {a}, {b} => [{", ".join(map(str,signed))}]\n'
    s += '''  | _, _, _ => []

/-- The signed Taylor numerator at order d. -/
def moment (h : Bool) (a b d : ℕ) : ℤ := (momentRow h a b).getD d 0

/-- The absolute fifth toroidal-frequency moment. -/
def fifth : Bool → ℕ → ℕ → ℤ
'''
    for height,a,b,_,fifth in rows:
        s += f'  | {height}, {a}, {b} => {fifth}\n'
    return s + '''  | _, _, _ => 0

end PlasmaLean.Design.DommaschkKamAInterfaceMoments
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    s = emit()
    if args.check:
        if OUTPUT.read_text() != s:
            raise ValueError('regenerate the moment table')
    else:
        OUTPUT.write_text(s)


if __name__ == '__main__':
    main()
