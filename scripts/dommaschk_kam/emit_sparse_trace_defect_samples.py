"""Build the selected physical polynomial residual packets for q0,u=.47."""
import argparse
from fractions import Fraction

from bounce_mirror_pilot import Model, R0M, angle_models
from bounce_phase_frame import FRAME_SCALE
from emit_sparse_reference_defect import HEADER
from emit_sparse_taylor_slab import DEST, RECORD, field, model_literal
from screen_sparse_reference_defects import enclosing_box, jobs, residual_models


def matrix_literal(entries):
    return '![' + ', '.join('!['+', '.join(f'{n}/{FRAME_SCALE}' for n in row)+']'
                            for row in entries) + ']'


def reference_columns(section, sign, i, coords):
    r, z = map(Model, coords)
    waves = angle_models(Fraction(sign*(2*i+1),128), Fraction(sign,128), Fraction(0))
    return [r-R0M, z, -waves[2] if section else waves[2], -waves[1] if section else waves[1]]


def emit_selected(requests, *, label='', launch=Fraction(47,100)):
    for job in requests:
        section, sign, i, coords, begin, end, budget, count = job
        name = 'DommaschkTraceResidual' + label + ('Back' if sign < 0 else 'Forward') + f'{i:03}'
        columns = reference_columns(section, sign, i, coords)
        phase = '(Real.pi / 2)' if section else '0'
        def prefix(deps):
            return (HEADER + ''.join('public import PlasmaLean.Design.'+d+'\n' for d in deps)
                    + f'\n/-! # Central reference residual for N-60, q={section}, u={launch}, '
                    + f'direction {sign}, slab {i}\n\nGenerated by '
                    + '`scripts/dommaschk_kam/emit_sparse_trace_defect_samples.py`. -/\n'
                    + '\n@[expose] public section\nnamespace PlasmaLean.Design.'+name+'\n'
                    + 'open PlasmaLean.Certificates.TrajectoryTaylorModel DommaschkKam DommaschkBounceTaylor\n'
                    + 'set_option linter.style.longLine false\nset_option Elab.async false\n'
                    + 'set_option maxRecDepth 16000\n\n')
        finish = '\nend PlasmaLean.Design.'+name+'\n'
        yield name+'Inputs', (prefix(['DommaschkBounceTaylor']) + '/-- Physical polynomial inputs. -/\n'
                               + 'def reference : Inputs := ⟨' + ',\n  '.join(map(model_literal, columns))
                               + '⟩\n' + finish)
        for which, suffix in [('dD','D'),('dnR','R'),('dnZ','Z')]:
            yield name+suffix, prefix([name+'Inputs']) + field(which, columns, 'reference') + finish
        transformed, denominator = residual_models(section, sign, i, coords, begin, end)
        rb, zb, dl = enclosing_box(transformed, denominator, count)
        assert rb*rb + zb*zb <= (Fraction(budget)*dl)**2 and dl > 0
        yield name+'Bounds', (prefix(['DommaschkFramedTaylorResidual']) +
            '/-- Enclosures for the two framed defect numerators and common denominator. -/\n'
            + 'def ratio : FramedTaylorResidual.Quotient := ⟨' +
            ',\n  '.join(map(model_literal, [*transformed, denominator])) + '⟩\n\n'
            + '/-- The submitted exact moving-frame defect budget for this slab. -/\n'
            + f'def budget : ℚ := {budget}\n\n'
            + '/-- Complete interval verification of the quotient-norm budget. -/\n'
            + f'theorem accepted : FramedTaylorResidual.Accepts ratio budget '
            + f'({rb}/2^80) ({zb}/2^80) ({dl}/2^80) [-3/4,-1/2,-1/4,0,1/4,1/2,3/4,1] := by\n'
            + '  constructor <;> kernel_fact\n' + finish)
        block, j = divmod(i, 8)
        count = min(8,391-block*8)
        back = 'true' if sign < 0 else 'false'
        extra = ['DommaschkOppositeHarmonic'] if section else []
        header = prefix([name+d for d in ('D','R','Z','Bounds')] + [f'DommaschkHarmonicBlock{block:02}', *extra])
        if section:
            harmonic = f'DommaschkOppositeHarmonic.first packet {back}'
            def membership(sine):
                component = 'sin' if sine == 'true' else 'cos'
                return f"""    · have model : reference.{component} = Certificates.TrajectoryTrig.negative
          ((packet {back} 0).model {sine}) := by
        apply Matches.eq
        constructor <;> apply eq_of_beq <;> kernel_fact
      rw [model]
      norm_num [Certificates.TrajectoryTrig.wave,sign,s] at {component} ⊢
      exact {component}"""
        else:
            harmonic = f'Certificates.TrajectoryHarmonicPacket.physical packet {back} 0'
            def membership(sine):
                component = 'sin' if sine == 'true' else 'cos'
                return f"""    · change ((packet {back} 0).model {sine}).Mem _ _
      norm_num [Certificates.TrajectoryTrig.wave,sign,s] at {component} ⊢
      exact {component}"""
        yield name, header + f'''open FramedTaylorResidual Certificates.QPoly
open Certificates.TrajectoryHarmonicPacket
open DommaschkBounceField

/-- The archived rational frame at the two physical slab endpoints. -/
def frame : Frame := Frame.ofEndpoints
  ({matrix_literal(begin)})
  ({matrix_literal(end)})

private theorem built :
    build ⟨7,80⟩ {back} 128 frame reference.u reference.z dnR0 dnZ0 dD0 = ratio := by
  apply Quotient.mk.injEq .. |>.mpr
  refine ⟨Matches.eq ?_, Matches.eq ?_, Matches.eq ?_⟩ <;>
    constructor <;> apply eq_of_beq <;> kernel_fact

/-- The physical Euclidean defect on the directed reference and its exported affine frame. -/
theorem physical_defect {{t : ℝ}} (ht : t ∈ Set.Icc ({i} / 64 : ℝ) ({i+1} / 64)) :
    let s := 128*t-{2*i+1}
    let v := physicalFlow {phase} ({sign} : ℝ) t (position reference s) - velocity reference 128 s
    let w := pulled frame s v
    Real.sqrt ((w 0)^2 + (w 1)^2) ≤ (budget:ℝ) := by
  let s := 128*t-{2*i+1}
  have hs : |s| ≤ 1 := abs_le.mpr ⟨by dsimp [s]; linarith [ht.1], by dsimp [s]; linarith [ht.2]⟩
  have hcert := accepted
  rw [← built] at hcert
  have coords (m : Model) (h : m.radius = 0) : m.Mem s (eval m.poly s) := by simp [Model.Mem,h]
  have hu : reference.u.Mem s (position reference s 0 - dkR0) := by
    simpa only [position, Matrix.cons_val_zero, add_sub_cancel_left] using
      coords reference.u (eq_of_beq (by kernel_fact))
  have hz : reference.z.Mem s (position reference s 1) := coords reference.z (eq_of_beq (by kernel_fact))
  have hr := enclose (c := ⟨[0], 1/2⟩) hs hu (by kernel_fact)
  have pos : 0 < position reference s 0 := by
    norm_num [Model.Mem,dkR0,abs_le] at hr
    linarith
  let packet := DommaschkHarmonicBlock{block:02}.packet ({j} : Fin {count})
  have ht' : t ∈ Set.Icc ((↑({8*block}+({j} : Fin {count}).val : ℕ) : ℝ)/64)
      (((↑({8*block}+({j} : Fin {count}).val : ℕ) : ℝ)+1)/64) := by norm_num at ht ⊢; exact ht
  have cos := {harmonic} false ht'
  have sin := {harmonic} true ht'
  have arg : reference.Mem s (position reference s 0 - dkR0) (position reference s 1)
      (Real.cos (2 * ({phase} + sign {back} * t))) (Real.sin (2 * ({phase} + sign {back} * t))) := by
    refine ⟨hu,hz,?_,?_⟩
{membership('false')}
{membership('true')}
  exact physical hcert dnR_checked dnZ_checked dD_checked t {phase} s hs pos arg
    ⟨by kernel_fact, by kernel_fact, by kernel_fact, by kernel_fact⟩
''' + finish


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sample = (job for job in jobs(RECORD, 8, sample=False)
              if (job[1],job[2]) in ((-1,0),(1,1),(1,390)))
    for name, source in emit_selected(sample):
        target = DEST / (name+'.lean')
        if args.check:
            if target.read_text() != source:
                raise SystemExit('regenerate ' + target.name)
        else:
            target.write_text(source)
