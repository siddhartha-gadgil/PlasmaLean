"""Join the per-slab lower Jacobian bounds of the wide-tube forward trace into one list predicate.

Writes `generated/qa2r_wide/WideTube/<Group>Lower.lean`: `PositionFrameTube.LowerOn` for the chunks
of 8 slabs used by `<Group>Joined` and for every prefix `all{j}` of the chain, composed with
`PositionFrameTube.lowerOn_append`. Build it with `lake build WideTube.<Group>Lower`.

    python3 scripts/qa2r_wide/assemble_lower.py --count 332
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def source(group, first, count, chunk):
    joined = group + "Joined"
    parts = []
    last = 0
    for j, lo in enumerate(range(0, count, chunk)):
        ks = list(range(lo, min(lo + chunk, count)))
        start = f"{group}.start" if lo == 0 else f"(next {group}.row{lo - 1})"
        items = []
        for i, k in enumerate(ks):
            clock = f"({first + lo} / 64 : ℝ)" + " + 1 / 64" * i
            head = f"  · rw [show {clock} = {first + k} / 64 by norm_num]\n    " if i else "  · "
            items.append(head + f"exact DommaschkWideTubeF{first + k:03}.neg_le_quadratic")
        parts.append(f"""
theorem lower{j} : LowerOn (velocityJacobian 0 1) {start} ({first + lo} / 64) {joined}.rows{j} := by
  refine ⟨{', '.join(['?_'] * len(ks))}, trivial⟩
{chr(10).join(items)}
""")
        if j == 0:
            parts.append(f"""
theorem lowerTo0 : LowerOn (velocityJacobian 0 1) {group}.start ({first} / 64) {joined}.all0 := lower0
""")
        else:
            parts.append(f"""
theorem lowerTo{j} : LowerOn (velocityJacobian 0 1) {group}.start ({first} / 64) {joined}.all{j} :=
  lowerOn_append {joined}.stepsTo{j - 1} lowerTo{j - 1}
    (by rw [{joined}.length{j - 1}]; norm_num) lower{j}
""")
        last = j
    return group + "Lower", f"""/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import WideTube.{joined}
public import PlasmaLean.Certificates.PositionFrameTube

/-! # Lower Jacobian bounds along forward slabs {first}–{first + count - 1} of the wide tube

Generated by `scripts/qa2r_wide/assemble_lower.py`. -/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{group}Lower

open Certificates PositionFrameSlabs PositionFrameTube DommaschkJacobian Set

set_option linter.style.longLine false
{''.join(parts)}
/-- The lower bound of every slab of the chain, in the order of `{joined}.rows`. -/
theorem lower : LowerOn (velocityJacobian 0 1) {group}.start ({first} / 64) {joined}.rows :=
  lowerTo{last}

end PlasmaLean.Design.{group}Lower
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", default="DommaschkWideTubeRows000")
    parser.add_argument("--first", type=int, default=0)
    parser.add_argument("--count", type=int, required=True)
    parser.add_argument("--chunk", type=int, default=8)
    args = parser.parse_args()
    name, text = source(args.group, args.first, args.count, args.chunk)
    path = ROOT / "generated/qa2r_wide/WideTube" / (name + ".lean")
    path.write_text(text)
    print(path)


if __name__ == "__main__":
    main()
