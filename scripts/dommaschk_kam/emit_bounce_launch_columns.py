"""Collapse the actual C/A packed Fourier grids at theta=0 for the mirror proofs.

The emitted Lean block equalities independently unpack and sum every coefficient.
Rows store signed numerators on the 2^128 scale, in order C-R, C-z, A-R, A-z.
"""
import argparse
import re
from fractions import Fraction
from pathlib import Path

from interface_arc import TORI
from hashlib import sha256


OUT = Path(__file__).resolve().parents[2] / 'PlasmaLean/Design/DommaschkMirrorLaunchData.lean'


def columns(tag, name):
    path, digest, _, _ = TORI[tag]
    raw = path.read_bytes()
    if sha256(raw).hexdigest() != digest:
        raise ValueError(f'packed {tag} grid changed')
    text = raw.decode()
    listing = re.search(r'def '+name+r' : List ℕ := \[(.*?)\]', text, re.S)[1]
    rows = [int(n, 16) for n in re.findall(r'0x[0-9a-fA-F]+', listing)]
    if len(rows) != 97 or any(n >> (125*161) for n in rows):
        raise ValueError(f'invalid grid dimensions for {tag}, {name}')
    mask = (1 << 125)-1
    half = [sum(((n >> (125*j)) & mask) - (1 << 124) for n in rows) for j in range(161)]
    sign = 1 if name == 'datU' else -1
    return [half[j]+sign*half[160-j] for j in range(161)]


def emit():
    labels = [('C', 'datU'), ('C', 'datZ'), ('A', 'datU'), ('A', 'datZ')]
    nums = [columns(*label) for label in labels]
    rows = list(zip(*nums, strict=True))
    out = ['''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkKamAInterfaceFourier
public import PlasmaLean.Certificates.IccListCert
public import Mathlib.Data.List.GetD

/-!
# Packed launch profiles of both Dommaschk tori

Generated by `emit_bounce_launch_columns.py`. The kernel checks 23 blocks
against the original packed grids. The signed frequencies run from -80 to 80.
-/

@[expose] public section
namespace PlasmaLean.Design.DommaschkMirrorLaunch

open DommaschkKamAInterfaceFourier PlasmaLean.Certificates.IccListCert

/-- Select one of the actual KAM coefficient grids. -/
def grid (outer vertical : Bool) : ℕ → ℕ → ℤ :=
  if outer then (if vertical then DommaschkKamA.gZ else DommaschkKamA.gU)
  else (if vertical then DommaschkKamC.gZ else DommaschkKamC.gU)

/-- Full transverse sum at one signed toroidal frequency. -/
def column (outer vertical : Bool) (m : ℤ) : ℤ :=
  ((List.range 193).map fun i => grid outer vertical i (m + 80).toNat).sum

/-- The checked list evaluator computes the numerator of the physical Fourier mode. -/
theorem slice_eq_column (o z : Bool) (m : ℤ) :
    sliceNumerator 96 80 (grid o z) 0 0 m = column o z m := by
  simp [sliceNumerator, sum_Icc_eq_list, column, List.map_congr_left]

/-- Four packed profiles in the order inner radius, inner height, outer radius, outer height. -/
def fourColumns (m : ℤ) : List ℤ :=
  [column false false m, column false true m, column true false m, column true true m]

/-- Seven adjacent frequencies form one kernel-replayed block. -/
def computed (i : ℕ) : List (List ℤ) :=
  (List.range 7).map fun j => fourColumns ((7*i+j : ℕ) - 80 : ℤ)

set_option linter.style.longLine false in
/-- Python's proposed coefficients; every entry is checked by `blocks_eq`. -/
def stored : ℕ → List (List ℤ)
''']
    for i in range(23):
        block = ',\n'.join('    '+str(list(row)) for row in rows[7*i:7*i+7])
        out.append(f'  | {i} => [\n{block}]\n')
    out.append('  | _ => []\n\nset_option maxRecDepth 12000\n')
    for i in range(23):
        out.append(f'\nset_option maxHeartbeats 4000000 in\nprivate theorem checked_{i} : '
                   f'computed {i} = stored {i} := by rfl\n')
    out.append('\n/-- All frequencies in the physical grid are covered by the verified blocks. -/\n'
               'theorem blocks_eq (i : Fin 23) : computed i = stored i := by\n  fin_cases i\n')
    out.extend(f'  · exact checked_{i}\n' for i in range(23))
    out.append('''
/-- Numerator of the signed mode in the validated table. -/
def weight (outer vertical : Bool) (m : ℤ) : ℤ :=
  let j := (m+80).toNat
  ((stored (j/7)).getD (j%7) []).getD ((if outer then 2 else 0)+(if vertical then 1 else 0)) 0

/-- Identify a seed coefficient with its checked integer. -/
theorem column_eq_weight (o z : Bool) {m : ℤ} (hm : m ∈ Finset.Icc (-80 : ℤ) 80) :
    column o z m = weight o z m := by
  obtain ⟨hl, hr⟩ := Finset.mem_Icc.mp hm
  let j := (m+80).toNat
  have hj : j < 161 := by dsimp [j]; omega
  let i : Fin 23 := ⟨j/7, by omega⟩
  have row : fourColumns m = (stored i).getD (j%7) [] := by
    rw [← blocks_eq]
    have hb : j%7 < (computed i).length := by simp [computed, Nat.mod_lt]
    rw [List.getD_eq_getElem _ _ hb]
    simp only [computed, List.getElem_map, List.getElem_range]
    congr 1
    dsimp [i,j]
    omega
  change _ = ((stored i).getD (j%7) []).getD _ 0
  rw [← row]
  cases o <;> cases z <;> rfl
''')
    # Section moment j=0 for the radius and j=1 for the vertical slope.
    for i,(tag,name) in enumerate(labels):
        base = nums[i]
        power = int(name == 'datZ')
        for opp in (False,True):
            value = sum(n*(2*m)**power*((-1)**(m%2) if opp else 1)
                        for m,n in zip(range(-80,81),base,strict=True))
            aux = f'{tag}{"Z" if power else "R"}{"Pi" if opp else "Zero"}'
            o,z=(str(tag=='A').lower(),str(bool(power)).lower())
            out.append(f'\n/-- Signed Fourier moment at the symmetry section for {tag}. -/\n'
                       f'theorem moment{aux} :\n'
                       f'    (∑ m ∈ Finset.Icc (-80 : ℤ) 80, weight {o} {z} m * '
                       f'(2*m)^{power} * ({"if m % 2 = 0 then 1 else -1" if opp else "1"})) =\n'
                       f'      {value} := by rw [sum_Icc_eq_list]; rfl\n')
        for b in (1,2):
            num = sum(abs(n*(2*m)**b) for m,n in zip(range(-80,81),base,strict=True))
            assert Fraction(num,2**128) < 10
            out.append(f'\n/-- Absolute frequency moment {b} for {tag} {name}. -/\n'
                       f'theorem abs{tag}{name}{b} :\n'
                       f'    (∑ m ∈ Finset.Icc (-80 : ℤ) 80, |weight {o} {z} m * (2*m)^{b}|) =\n'
                       f'      {num} := by rw [sum_Icc_eq_list]; rfl\n')
    out.append('\nend PlasmaLean.Design.DommaschkMirrorLaunch\n')
    return ''.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = emit()
    if args.check:
        if OUT.read_text() != text:
            raise SystemExit('regenerate the launch certificate')
    else:
        OUT.write_text(text)
