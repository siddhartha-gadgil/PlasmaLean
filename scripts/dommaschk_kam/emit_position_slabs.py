"""Generate Lean scalar frame proofs from the exact N-60 witnesses.

The default regenerates the two checked-in pilot modules. --verify-all rebuilds
and kernel-checks all 16 chains in a temporary directory. --all --output-dir
retains importable Lean sources for every endpoint. All modes use the exact
same emitter, and the pilot retains its sharper matrix and radius thresholds.
"""
import argparse
import gzip
import json
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from fractions import Fraction
from math import isqrt
from pathlib import Path
from tempfile import TemporaryDirectory


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'scripts/dommaschk_kam/results/bounce_frame_q0_u470.json.gz'
DEST = ROOT / 'PlasmaLean/Design'
ARCHIVE = SOURCE.parent / 'bounce_local_graphs_20261123.json'


def integer(x):
    return str(x) if x >= 0 else f'({x})'


def rational(value):
    f = Fraction(value)
    if f.denominator == 1:
        return integer(f.numerator)
    return f'({integer(f.numerator)} / {f.denominator})'


def ctor(entries):
    return '⟨'+', '.join(entries)+'⟩'


def frame(matrix):
    return ctor([integer(x) for row in matrix for x in row])


def state(point, matrix, radius):
    return ctor([ctor(list(map(integer,point))),frame(matrix),integer(radius)])


def step(w):
    columns = ', '.join('['+', '.join(map(integer,p))+']' for p in w['coefficients'])
    vectors = frame(w['frame_end'])+', '+ctor(list(map(integer,w['jump'])))
    radii = ', '.join(str(w[k]) for k in ('jump_norm_upper','frame_radius_in','frame_radius_out',
            'frame_trial_radius','physical_radius_in','physical_radius_out','physical_trial_radius'))
    scalars = ', '.join(rational(w[k]) for k in ('determinant_lower','frame_norm_upper',
                                                  'log_norm_upper','defect_upper'))
    return '  ⟨'+',\n   '.join((columns,vectors,radii,scalars))+'⟩'


def emit(header, trace):
    sign = trace['direction']
    q = header['section_in_half_pi']
    u = Fraction(header['launch_u'])
    index = int(1000*u)
    pilot = q == 0 and index == 470
    limits = 'pilotLimits' if pilot else 'allLimits'
    name = 'DommaschkPositionFrames'+('' if pilot else f'Q{q}R{index}')+('Back' if sign == -1 else 'Fwd')
    rows = trace['steps']
    if len(rows) != 391 or any(row['index'] != i for i,row in enumerate(rows)):
        raise ValueError('non-consecutive position slabs')
    blocks = [rows[i:i+16] for i in range(0,len(rows),16)]
    center = [c[0] for c in header['seed_center_radius']]
    error = [c[1] for c in header['seed_center_radius']]
    radius = isqrt(sum(r*r for r in error))+1
    fs = header['frame_denominator']
    initial = state(center,[[fs,0],[0,fs]],radius)
    lines = [f'''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkMirrorEndpoints

/-!
# Exact position-frame replay on the q={q}, u=0.{index:03d} trace, direction {sign}

Generated by `emit_position_slabs.py` from the saved two-sided witness. Every
coefficient, matrix entry, radius and fraction comes directly from the record.
-/

@[expose] public section
namespace PlasmaLean.Design.{name}

open PlasmaLean.Certificates.PositionFrameSlabs

set_option linter.style.longLine false

/-- Transferred seed centre, initial identity frame and Euclidean radius. -/
def start : State := {initial}

/-- The physical section-entry theorem uses precisely this seed and initial frame. -/
theorem shared_start : start = DommaschkMirrorLaunch.MirrorEndpoint.start .q{q}r{index} := rfl

/-- The two coordinate uncertainties fit in the initial transformed ball. -/
theorem seed_bounds : {error[0]}^2 + {error[1]}^2 ≤ start.radius^2 := by
  norm_num [start]
''']
    prior='start'
    for i,block in enumerate(blocks):
        label = f'block{i}'
        end=f'state{i+1}'
        tail=block[-1]
        next_point=[sum(p) for p in tail['coefficients']]
        next_state=state(next_point,tail['frame_end'],tail['frame_radius_out'])
        lines.append(f'/-- Signed dyadic data for slabs {block[0]["index"]}–{tail["index"]}. -/\n'
                     f'def {label} : List Step := [\n'+',\n'.join(map(step,block))+']\n')
        lines.append(f'/-- Shared state after {tail["index"]+1} slabs. -/\n'
                     f'def {end} : State := {next_state}\n')
        lines.append(f'private theorem check{i} : run {limits} {prior} {label} = (true, {end}) := by\n'
                     '  with_unfolding_all rfl\n')
        prior=end
    lines.append('/-- Ordered source blocks covering the full length 391/64. -/\n'
                 'def blocks : List (List Step) := ['+', '.join(f'block{i}' for i in range(len(blocks)))+']\n')
    lines.append(f'/-- The scalar propagation from the transferred ball through the final slab. -/\n'
                 f'theorem checked : Chain {limits} start blocks 391 {prior} := by\n  unfold blocks')
    for i,block in enumerate(blocks):
        left = len(rows)-block[-1]['index']-1
        lines.append(f'  refine Chain.cons (n := {left}) check{i} ?_')
    lines.extend(['  exact .nil _','',f'end PlasmaLean.Design.{name}',''])
    return name,'\n'.join(lines)


def sources(all_endpoints):
    if not all_endpoints:
        return [(0,Fraction(47,100),SOURCE)]
    archive = json.loads(ARCHIVE.read_text())
    keys = [(s['section_in_half_pi'],Fraction(r['launch_radius'])) for s in archive['sections']
            for r in s['endpoints']]
    if len(keys) != 8 or len(set(keys)) != 8:
        raise ValueError('expected eight distinct source endpoints')
    return [(q,u,SOURCE.parent/f'bounce_frame_q{q}_u{int(1000*u)}.json.gz') for q,u in keys]


def render(source,q,u):
    packet=json.loads(gzip.decompress(source.read_bytes()))
    if (packet['format'] != 'DommaschkN60Frame/v1' or packet['launch_u'] != str(u)
            or packet['section_in_half_pi'] != q or packet['step'] != '1/64'
            or packet['coordinate_denominator'] != 2**80 or packet['frame_denominator'] != 2**40
            or [t['direction'] for t in packet['traces']] != [-1,1]):
        raise ValueError('unexpected witness schema, scales, endpoint or direction')
    for trace in packet['traces']:
        yield emit(packet,trace)


def verify(path):
    result = subprocess.run(['lake','env','lean','-DwarningAsError=true',str(path)],cwd=ROOT,
                            capture_output=True,text=True)
    if result.returncode:
        raise RuntimeError(path.name+'\n'+result.stdout+result.stderr)
    audits = re.findall(r"depends on axioms: \[([^\]]*)\]",result.stdout)
    if len(audits) != 2 or any(set(r.split(', '))-{'propext','Classical.choice','Quot.sound'}
                              for r in audits):
        raise ValueError('missing or unexpected axiom audit in '+path.name+'\n'+result.stdout)
    return path.name


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check',action='store_true',help='compare sources with the stored records')
    mode.add_argument('--verify-all',action='store_true',help='kernel-check all 16 chains and their axioms')
    parser.add_argument('--all',action='store_true',help='write all 16 sources to --output-dir')
    parser.add_argument('--output-dir',type=Path)
    parser.add_argument('--jobs',type=int,choices=range(1,9),default=1,help='Lean workers for --verify-all')
    args = parser.parse_args()
    if args.jobs != 1 and not args.verify_all:
        parser.error('--jobs applies to --verify-all')
    if args.verify_all and (args.all or args.output_dir):
        parser.error('--verify-all uses temporary audit sources')
    if args.all and not args.output_dir:
        parser.error('--all requires an explicit --output-dir')
    with TemporaryDirectory() as scratch:
        dest = Path(scratch) if args.verify_all else (args.output_dir or DEST)
        dest.mkdir(parents=True,exist_ok=True)
        files = []
        for q,u,source in sources(args.all or args.verify_all):
            for name,text in render(source,q,u):
                path = dest/(name+'.lean')
                if args.check:
                    if path.read_text() != text:
                        raise ValueError(f'{name} differs from exported records')
                    continue
                if args.verify_all:
                    text += (f'\n#print axioms PlasmaLean.Design.{name}.seed_bounds\n'
                             f'#print axioms PlasmaLean.Design.{name}.checked\n')
                path.write_text(text)
                files.append(path)
        if args.verify_all:
            subprocess.run(['lake','build','--fail-fast','PlasmaLean.Design.DommaschkMirrorEndpoints'],
                           check=True,cwd=ROOT)
            with ThreadPoolExecutor(max_workers=args.jobs) as pool:
                for completed in pool.map(verify,files):
                    print(f'Checked {completed}',flush=True)


if __name__ == '__main__':
    main()
