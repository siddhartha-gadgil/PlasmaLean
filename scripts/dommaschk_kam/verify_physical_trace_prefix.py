"""Prove one physical Q-16 trajectory through a forward prefix of the saved pilot.

The first two rows use the checked-in physical modules. Further rows are
authenticated and assembled by verify_physical_trace_slabs.py. The final Lean
proof composes their actual ellipsoids and ODE bounds at each exact clock.
"""

import argparse
import fcntl
import gzip
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from tempfile import TemporaryDirectory

from verify_physical_trace_slabs import ALLOWED, DESIGN, HERE, PACKAGE, RECORD, ROOT
from verify_physical_trace_slabs import artifact_hashes, digest, key_of, run_lean, save


PREFIX_PACKAGE = 'PhysicalPrefixCache'
IMPORTS = ('DommaschkMirrorFramePath', 'DommaschkPhysicalSecondStep')
THEOREMS = ('checked', 'field_bounds', 'exists_nested_prefix', 'uniform_tube_error')


def prefix_source(length):
    with gzip.open(RECORD, 'rt') as fp:
        packet = json.load(fp)
    forward, = [trace for trace in packet['traces'] if trace['direction'] == 1]
    maximum = max(row['physical_radius_out'] for row in forward['steps'][:length])
    modules = ['DommaschkPhysicalFirstStep','DommaschkPhysicalSecondStep',
               *(f'DommaschkPhysicalForward{i:03}' for i in range(2,length))]
    name = f'DommaschkPhysicalPrefix{length:03}'
    header = '\n'.join('public import PlasmaLean.Design.'+m for m in IMPORTS)
    header += ''.join('\npublic import '+PACKAGE+'.'+m for m in modules[2:])
    lines = [f'''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

{header}

/-! # Physical Q-16 birth and {length} consecutive QA2R forward slabs
Generated by `verify_physical_trace_prefix.py`. -/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{name}

open Certificates.PositionFrameSlabs DommaschkMirrorLaunch DommaschkKamC KamNewton
open PlasmaLean.Contract PlasmaLean.Forms PlasmaLean.Fields.VacuumBoozer
open PlasmaLean.Theory.KAM WEll1Z2

set_option maxRecDepth 4096

/-- Chronological list of the actual saved position-frame rows. -/
def rows : List Step := [''', ',\n  '.join(m+'.row' for m in modules)+']',
           f'/-- Exact final state after {length} steps. -/\nabbrev exitState := next {modules[-1]}.row',
           '''
private theorem cons_run {s e : State} {r : Step} {tail : List Step}
    (h : test pilotLimits s r = true) (rest : run pilotLimits (next r) tail = (true, e)) :
    run pilotLimits s (r::tail) = (true, e) := by simp only [run, rest, h, Bool.and_true]

private theorem cons_bounds (i : ℕ) {s : State} {r : Step} {tail : List Step}
    (h : FieldBounds s r ((i:ℝ)/64) (DommaschkJacobian.euclideanFlow 0 1)
      (DommaschkJacobian.velocityJacobian 0 1) ballDomain)
    (rest : FieldBoundsOn (DommaschkJacobian.euclideanFlow 0 1)
      (DommaschkJacobian.velocityJacobian 0 1) (next r) ((i+1:ℕ)/64) tail ballDomain) :
    FieldBoundsOn (DommaschkJacobian.euclideanFlow 0 1) (DommaschkJacobian.velocityJacobian 0 1)
      s ((i:ℝ)/64) (r::tail) ballDomain := by
  refine ⟨h,?_⟩
  have clock : (i:ℝ)/64 + 1/64 = ((i+1:ℕ):ℝ)/64 := by push_cast; ring
  rw [clock]
  exact rest
''', f'''/-- Accepted scalar states agree exactly at every recorded join. -/
theorem checked : Chain pilotLimits (MirrorEndpoint.start .q0r470) [rows] {length} exitState := by
  apply Chain.cons (m := exitState) (n := 0)
  · unfold rows''']
    lines += [f'    refine cons_run {m}.checked ?_' for m in modules]
    lines += ['    rfl', '  · exact .nil _','''
/-- Every member of the chronological prefix has a physical QA2R theorem at its own clock. -/
theorem field_bounds :
    FieldBoundsOn (DommaschkJacobian.euclideanFlow 0 1) (DommaschkJacobian.velocityJacobian 0 1)
      (MirrorEndpoint.start .q0r470) 0 rows ballDomain := by
  unfold rows
  conv in FieldBoundsOn _ _ _ 0 _ _ =>
    arg 4
    rw [show (0 : ℝ) = (0:ℕ)/64 by norm_num]''']
    for i,m in enumerate(modules):
        field = 'ball_field_bounds' if i == 0 else 'field_bounds'
        clock = '0' if i == 0 else f'{i}/64'
        lines += [f'  refine cons_bounds {i} ?_ ?_',
                  f'  · rw [show (({i}:ℕ):ℝ)/64 = {clock} by norm_num]',
                  f'    with_unfolding_all exact {m}.{field}']
    lines += ['  trivial', f'''
/-- The same nested Q-16 surface pair admits this physical forward trajectory
for every birth within 2⁻¹⁹ radian of the common section. -/
theorem exists_nested_prefix :
    ∃ (uC zC uA zA : FA) (R₀ z₀ : ℝ → ℝ) (ΘC ΘA : ℝ → ℝ → ℝ),
      IotaOnTorus (DommaschkQA2R.field DommaschkQA2R.candidate)
        (RofC uC) (Zof zC) DommaschkKamDio.dkIotaC ∧
      IotaOnTorus (DommaschkQA2R.field DommaschkQA2R.candidate)
        (RofC uA) (Zof zA) DommaschkKamDio.dkIotaA ∧
      DommaschkKamNested.NestedTori (RofC uC) (Zof zC) (RofC uA) (Zof zA) R₀ z₀ ΘC ΘA ∧
      ∀ φ : ℝ, |φ| ≤ 1 / 2^19 → FollowsFrames .q0r470 uC zC uA zA φ 1 {length} exitState rows := by
  obtain ⟨uC,zC,uA,zA,R₀,z₀,ΘC,ΘA,ic,ia,nested,paths⟩ := exists_nested_frame_paths
  refine ⟨uC,zC,uA,zA,R₀,z₀,ΘC,ΘA,ic,ia,nested,fun φ hp => ?_⟩
  exact paths .q0r470 φ 1 (by
    simpa [MirrorEndpoint.width, MirrorEndpoint.opposite, azimuth] using hp)
    {length} pilotLimits exitState [rows] checked field_bounds

/-- Largest outward-rounded Euclidean radius among these recorded slabs, in units of 2⁻⁸⁰. -/
def maximumRadius : ℕ := {maximum}

private theorem radius_le {{r : Step}} (h : r ∈ rows) : r.physicalOut ≤ maximumRadius := by
  have all : rows.all (fun e => e.physicalOut.ble maximumRadius) = true := by
    with_unfolding_all rfl
  exact Nat.ble_eq.mp ((List.all_eq_true.mp all) r h)

private theorem reference_of_slab {{s : State}} {{a : ℝ}} {{rs : List Step}}
    {{slab : Fields.TrajectorySlabs.Slab Plane}} (hs : slab ∈ physicalSlabs s a rs) :
    ∃ r ∈ rs, ∀ t y, y ∈ slab.tube t →
      dist y (reference slab.start r t) ≤ r.physicalOut/(2:ℝ)^80 := by
  induction rs generalizing s a with
  | nil => simp [physicalSlabs] at hs
  | cons r rs ih =>
    rcases List.mem_cons.mp hs with rfl | tail
    · exact ⟨r,List.Mem.head _,fun _ _ h => h.2⟩
    · obtain ⟨q,hq,bound⟩ := ih tail
      exact ⟨q,List.Mem.tail _ hq,bound⟩

/-- On every slab the true Euclidean error about its own stored polynomial is
bounded by the maximum physical radius of the chronological prefix. -/
theorem uniform_tube_error {{path : ℝ → Plane}}
    (inside : ∀ slab ∈ physicalSlabs (MirrorEndpoint.start .q0r470) 0 rows,
      ∀ t ∈ Set.Icc slab.start slab.stop, path t ∈ slab.tube t) :
    ∀ slab ∈ physicalSlabs (MirrorEndpoint.start .q0r470) 0 rows,
      ∃ r ∈ rows, ∀ t ∈ Set.Icc slab.start slab.stop,
        dist (path t) (reference slab.start r t) ≤ maximumRadius / (2 : ℝ)^80 := by
  intro slab hs
  obtain ⟨r,hr,bound⟩ := reference_of_slab hs
  refine ⟨r,hr,fun t ht => (bound t _ (inside slab hs t ht)).trans ?_⟩
  exact div_le_div_of_nonneg_right (by exact_mod_cast radius_le hr) (by positivity)

end PlasmaLean.Design.{name}
''']
    return name,'\n'.join(lines),maximum


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--length',type=int,default=8)
    parser.add_argument('--cache',type=Path,default=ROOT/'.lake/physical-frame-checks')
    parser.add_argument('--residual-cache',type=Path,default=ROOT/'.lake/trace-residual')
    parser.add_argument('--jacobian-cache',type=Path,default=ROOT/'.lake/jacobian-checks')
    parser.add_argument('--wait-seconds',type=int,default=0)
    parser.add_argument('--output',type=Path)
    args = parser.parse_args()
    if not 2 <= args.length <= 391 or args.wait_seconds < 0:
        parser.error('length must be 2..391 and the wait nonnegative')
    args.cache = args.cache.resolve()
    with TemporaryDirectory() as temporary:
        rows = {'rows':[]}
        if args.length > 2:
            manifest = Path(temporary)/'rows.json'
            subprocess.run([sys.executable,str(HERE/'verify_physical_trace_slabs.py'),
                            '--range','2',str(args.length-1),'--cache',str(args.cache),
                            '--residual-cache',str(args.residual_cache),'--jacobian-cache',
                            str(args.jacobian_cache),'--wait-seconds',str(args.wait_seconds),
                            '--output',str(manifest)],cwd=ROOT,check=True)
            rows = json.loads(manifest.read_text())
    subprocess.run(['lake','build','--no-build',*['PlasmaLean.Design.'+m for m in IMPORTS]],
                   cwd=ROOT,check=True,stdout=subprocess.DEVNULL)
    def lake(*cmd):
        return subprocess.check_output(['lake','env',*cmd],cwd=ROOT,text=True).strip()
    version = lake('lean','--version')
    compiler = str(Path(lake('lean','--print-prefix'))/'bin/lean')
    name,source,maximum = prefix_source(args.length)
    deps = [(m,digest(DESIGN/(m+'.trace'))) for m in IMPORTS]
    keys = [r['key'] for r in rows['rows']]
    key = key_of([digest(RECORD),version,deps,source,keys])
    work = args.cache/name/key
    tree = work/PREFIX_PACKAGE
    tree.mkdir(parents=True,exist_ok=True)
    marker = work/'accepted.json'
    paths = [str(work),*([rows['imports']] if keys else []),lake('printenv','LEAN_PATH')]
    with (work/'lock').open('w') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        if marker.is_file():
            result = json.loads(marker.read_text())
            if result['key'] != key or result['length'] != args.length or result['module'] != name:
                raise ValueError(f'incorrect prefix manifest: {marker}')
            artifact_hashes(work,result)
        else:
            src,obj = tree/(name+'.lean'),tree/(name+'.olean')
            src.write_text(source)
            cmd = [compiler,'-j1','-DwarningAsError=true','-R',str(work)]
            env = {**os.environ,'LEAN_NUM_THREADS':'1','LEAN_PATH':os.pathsep.join(paths)}
            seconds,rss = run_lean([*cmd,'-o',str(obj),str(src)],env,work/'peak.txt',work/'prefix.log')
            audit = work/'Audit.lean'
            audit.write_text(f'import {PREFIX_PACKAGE}.{name}\n'+''.join(
                f'#print axioms PlasmaLean.Design.{name}.{t}\n' for t in THEOREMS))
            audit_log = work/'audit.log'
            elapsed,peak = run_lean([*cmd,str(audit)],env,work/'peak.txt',audit_log)
            for theorem in THEOREMS:
                m = re.search(re.escape(f"PlasmaLean.Design.{name}.{theorem}'")
                              +r' depends on axioms:\s*\[([^]]*)\]',audit_log.read_text())
                if not m or set(map(str.strip,m[1].split(','))) != ALLOWED:
                    raise ValueError(f'{theorem}: bad axiom audit')
            files = [src,audit,audit_log,*tree.glob(name+'.olean*')]
            result = {'key':key,'module':name,'length':args.length,'lean_version':version,
                      'packet_sha256':digest(RECORD),'row_keys':keys,'theorems':list(THEOREMS),
                      'max_physical_radius_numerator':maximum,'coordinate_denominator':2**80,
                      'axioms':sorted(ALLOWED),'wall_seconds':round(seconds+elapsed,3),
                      'peak_rss_kib':max(rss,peak),'import_paths':paths[:-1],
                      'artifacts':{str(f.relative_to(work)):digest(f) for f in files}}
            save(marker,result)
    public = {k:v for k,v in result.items() if k != 'artifacts'}
    if args.output:
        save(args.output,public)
    print(json.dumps(public),flush=True)


if __name__ == '__main__':
    main()
