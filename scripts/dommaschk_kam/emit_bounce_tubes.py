"""Emit a Lean certificate for both launch tubes of the physical QA2R flow.

Outward rounding uses integer division throughout. Each emitted block equality
is checked against the field data in Lean; the input file is its own source of
coefficients, so no numerical proposal or rounded field parameters are used.
"""
from fractions import Fraction
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "PlasmaLean/Design/DommaschkKamFieldData.lean"
OUTPUT = ROOT / "PlasmaLean/Design/DommaschkBounceTubeData.lean"
S = 1 << 32
BOXES = {
    "outer": ((5*S//64, 7*S//64), (-S//64,S//64), (15*S//16,S), (-S//16,S//16)),
    "inner": ((-S//32, 0), (-S//64,S//64), (-S,-15*S//16), (-S//16,S//16)),
}


def coefficients(source, name):
    table = source.split(f"def {name} : SP := [", 1)[1].split("]", 1)[0]
    values = re.findall(r"⟨mkRat \((-?\d+)\)\s+(\d+), (\d+), (\d+), (\d+), (\d+)⟩", table)
    if len(values) != table.count("⟨"):
        raise ValueError(f"malformed {name} term")
    return [(Fraction(int(p), int(q)), tuple(map(int, exps))) for p, q, *exps in values]


def mul(x, y):
    products = [a*b for a in x for b in y]
    return min(products)//S, -((-max(products))//S)


def power(interval, exponent):
    result = (S, S)
    for _ in range(exponent):
        result = mul(result, interval)
    return result


def monomial(box, coefficient, exponents):
    values = [power(interval, exp) for interval, exp in zip(box, exponents, strict=True)]
    v = mul(mul(mul(values[0], values[1]), values[2]), values[3])
    q = coefficient * S
    return mul((q.__floor__(), q.__ceil__()), v)


def interval(pair):
    return f"⟨{pair[0]}, {pair[1]}, true⟩"


def main():
    source = DATA.read_text()
    text = ['''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkBounceField
public import PlasmaLean.Certificates.KernelFact

/-! # Checked field enclosures on the two deep-well launch tubes
Generated by `scripts/dommaschk_kam/emit_bounce_tubes.py`.
-/

@[expose] public section

namespace PlasmaLean.Design.DommaschkBounceField
open PlasmaLean.Design.DommaschkKam DkPoly
open PlasmaLean.Certificates.ValidatedQuadrature

set_option maxRecDepth 65536
set_option maxHeartbeats 8000000
''']
    for label, box in BOXES.items():
        text.append(f"/-- Shifted cylindrical coordinates and trigonometric box for the {label} launch. -/")
        text.append(f"def {label}Box : Box := ⟨" + ", ".join(map(interval, box)) + "⟩\n")
        for name in ("dD", "dnR", "dnZ"):
            vals = [monomial(box, q, e) for q, e in coefficients(source, name)]
            total = tuple(sum(p[i] for p in vals) for i in (0, 1))
            print(label, name, total, [float(Fraction(x,S)) for x in total])
            text.append(f"/-- Exact outward-rounded enclosure for all {len(vals)} terms. -/")
            text.append(f"theorem {label}_{name} : polyBox {label}Box {name} = {interval(total)} := by")
            text.append("  apply BlockCheck.eq")
            tail = total
            for start in range(0, len(vals), 8):
                part = vals[start:start+8]
                subtotal = tuple(sum(p[i] for p in part) for i in (0, 1))
                tail = tuple(x-y for x,y in zip(tail,subtotal))
                text.append(f"  refine BlockCheck.chunk {len(part)} {interval(subtotal)} {interval(tail)} (by kernel_fact) rfl ?_")
            text.append("  exact BlockCheck.nil\n")
    text.append("end PlasmaLean.Design.DommaschkBounceField\n")
    OUTPUT.write_text("\n".join(text))


if __name__ == "__main__":
    main()
