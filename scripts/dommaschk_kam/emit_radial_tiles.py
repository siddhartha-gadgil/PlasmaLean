"""Generate Lean proof terms for all 32 directed N-60 radial summary records.

This generator uses only exact integer/rational proposals. The generated interval
comparisons are proved in Lean, including the two sides of each dyadic rounding
and the common endpoints of every neighbouring radial tile.
"""
import argparse
from fractions import Fraction as F
import json
from math import ceil, isqrt
from pathlib import Path


HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / 'PlasmaLean' / 'Design' / 'DommaschkRadialTiles.lean'
SCALE = 1 << 80
HEIGHTS = [F('1.0595923312168822'), F('1.0601092782791866')]
SOURCES = ('bounce_radial_arcs_20261123.json', 'bounce_radial_arcs_opposite_20261123.json')
BRACKETS = (((523, 531), (470, 478)), ((509, 517), (456, 464)))


def rat(value):
    return f'({value.numerator} / {value.denominator})'


def roots(value):
    if value < 0:
        raise ValueError('negative radicand')
    numerator = isqrt(int(value*SCALE**2))
    return F(numerator, SCALE), F(numerator + (numerator**2 != value*SCALE**2), SCALE)


def numbers(run):
    raw = [v for name in ('B2', 'A2', 'B2_u', 'A2_u') for v in run['bounds'][name]]
    b0,b1,a0,a1,db0,db1,da0,da1 = [F(x, SCALE) for x in raw]
    cap, end, orient = (run['core_B2_upper_numerator'], run['end_B2_lower_numerator'],
                        run['outward_B2_slope_lower_numerator'])
    if not (0 < b0 <= b1 and 0 < a0 <= a1 and db0 <= db1 < 0 and 0 < da0 <= da1
            and F(cap, SCALE) < HEIGHTS[0]**2 and HEIGHTS[1]**2 < F(end, SCALE)
            and 0 < orient and run['steps'] == ceil(F(61,10)*64)):
        raise ValueError('invalid signs, cap, or trace length')
    bmin, bmax = roots(b0)[0], roots(b1)[1]
    amplitude = roots(2*a1*(HEIGHTS[1]-bmin))[1]
    slope = int(SCALE*a0*(-db1)/(2*amplitude*bmax))
    if not 0 < slope == run['core_radial_action_slope_lower_numerator']:
        raise ValueError('wrong outward slope or rounding')
    return raw + [cap, end, orient] + [int(x*SCALE) for x in (bmin,bmax,amplitude)] + [slope]


def generate():
    out = ['''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Certificates.RadialTile

/-!
# Exact radial tile arithmetic on the two N-60 Dommaschk sectors

Generated by `scripts/dommaschk_kam/emit_radial_tiles.py` from the two
`bounce_radial_arcs*` packets. Each half trace uses directed bounds on squared
quantities. Physical inclusion of the traces in these bounds is the separate
`Half.Encloses` input to `Cover.action_secant`.
-/

@[expose] public section
noncomputable section

namespace PlasmaLean.Design.DommaschkRadialTiles

open Certificates.RadialTile

/-- The smaller dimensionless mirror height. -/
def low : ℝ := 5297961656084411 / 5000000000000000

/-- The larger dimensionless mirror height. -/
def high : ℝ := 5300546391395933 / 5000000000000000

/-- The certificate's signed fixed-point quantities have eighty fractional bits. -/
def dyadic (n : ℤ) : ℝ := (n : ℝ) / 1208925819614629174706176
''']
    for section, file in enumerate(SOURCES):
        data = json.loads((HERE/'results'/file).read_text())
        if (data['section_in_half_pi'] != section or data['scale'] != SCALE or
                list(map(F, data['heights'])) != HEIGHTS or F(data['alpha_half_width']) != F(1,4096)
                or F(data['limit']) != F(61,10) or F(data['core_limit']) != 1 or
                not data['common_section'] or len(data['brackets']) != 2):
            raise ValueError('incompatible sector')
        for height, bracket in enumerate(data['brackets']):
            left,right = [F(v,1000) for v in BRACKETS[section][height]]
            if (bracket['height_index'] != height or list(map(F,bracket['u'])) != [left,right]
                    or len(bracket['tiles']) != 4):
                raise ValueError('incompatible radial bracket')
            tag = f's{section}h{height}'
            pos = left
            minima = []
            for tile_index,tile in enumerate(bracket['tiles']):
                c,w = F(tile['u_center']),F(tile['u_half_width'])
                if (pos != c-w or w <= 0 or tile['scale'] != SCALE or not tile['common_section']
                        or tile['section_in_half_pi'] != section or list(map(F,tile['heights'])) != HEIGHTS
                        or F(tile['alpha_half_width']) != F(1,4096) or F(tile['limit']) != F(61,10)
                        or F(tile['core_limit']) != 1 or F(tile['step']) != F(1,64)
                        or [run['direction'] for run in tile['runs']] != [-1,1]):
                    raise ValueError('incompatible tile')
                pos = c+w
                tile_id = f'{tag}p{tile_index}'
                total = 0
                for suffix,run in zip(('back','fwd'),tile['runs'],strict=True):
                    name = tile_id+suffix
                    vals = numbers(run)
                    total += vals[-1]
                    out.extend([f'/-- {file}, height {height}, tile {tile_index}, direction {run["direction"]}. -/',
                                f'def {name} : Half :='])
                    entries = [f'dyadic ({n})' if n<0 else f'dyadic {n}' for n in vals]
                    entries.append(str(run['steps']))
                    for i in range(0,len(entries),2):
                        end = '⟩' if i+2 == len(entries) else ','
                        out.append(('  ⟨' if i==0 else '   ')+', '.join(entries[i:i+2])+end)
                    out.extend(['', '/-- The kernel checks all signs, square brackets, and both rounding inequalities. -/',
                                f'theorem {name}_valid :',
                                f'    {name}.Valid low high (dyadic 1) (1/64) (61/10) := by',
                                f'  constructor <;> norm_num [{name}, dyadic, low, high]', ''])
                if total != tile['radial_action_secant_lower_numerator']:
                    raise ValueError('incorrect two-direction sum')
                minima.append(total)
                out.extend([f'/-- Radial tile centred at {c}, including both endpoints. -/',
                            f'def {tile_id} : Piece :=',
                            f'  ⟨{rat(c-w)}, {rat(c+w)}, {tile_id}back, {tile_id}fwd⟩',''])
            if pos != right or F(min(minima),SCALE) != F(bracket['radial_action_secant_lower']):
                raise ValueError('incorrect cover or minimum')
            names = [f'{tag}p{i}' for i in range(4)]
            out.extend(['/-- The complete ordered radial tile list for this bracket. -/',
                        f'def {tag} : List Piece := [{", ".join(names)}]','',
                        '/-- The weakest total secant in this four-tile bracket. -/',
                        f'def {tag}Slope : ℝ := dyadic {min(minima)}', '',
                        '/-- All eight half-trace summaries validate and every radial endpoint matches. -/',
                        f'theorem {tag}_cover : Cover low high (dyadic 1) (1/64) (61/10) {tag}Slope',
                        f'    {rat(left)} {rat(right)} {tag} := by',
                        f'  unfold {tag}'])
            for name in names:
                out.extend([f'  apply Cover.cons {name} (by norm_num [{name}])',
                            f'    {name}back_valid {name}fwd_valid',
                            f'    (by norm_num [{name}, {name}back, {name}fwd, {tag}Slope, dyadic])'])
            out.extend(['  exact Cover.nil _', ''])
    return '\n'.join(out)+'\nend PlasmaLean.Design.DommaschkRadialTiles\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('radial tile proof artifact differs')
    else:
        OUTPUT.write_text(text)
