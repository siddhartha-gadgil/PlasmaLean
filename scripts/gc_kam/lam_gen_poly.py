def emit(name, expr, doc):
    P = sp.Poly(sp.expand(expr), u, z, c, s)
    den = 1
    for _, co in P.terms():
        den = sp.ilcm(den, sp.Rational(co).q)
    terms = sorted(P.terms(), key=lambda t: (-sum(t[0]), t[0]))
    lines = []
    for (i, j, k, l), co in terms:
        mono = ['(%d, %d)' % (idx, e) for idx, e in enumerate((i, j, k, l)) if e]
        cc = sp.Rational(co) * den
        assert cc.q == 1
        lines.append('    monoE (%d) [%s]' % (int(cc), ', '.join(mono)))
    body = 'sumE [\n%s]' % ',\n'.join(lines)
    if den != 1:
        return '/-- %s -/\ndef %s : PolyExpr ℂ (Fin 6) := mul (const (1 / %d)) (%s)\n' % (doc, name, den, body)
    return '/-- %s -/\ndef %s : PolyExpr ℂ (Fin 6) := %s\n' % (doc, name, body)


