"""Collect the generated QA2R Lean modules cited in the notes, with their import closure.

The campaign scripts in `scripts/dommaschk_kam/` write Lean sources into caches under `.lake/`
(ignored by git). This script copies the sources that the notes cite, and every generated module
they import, to `generated/qa2r/<Package>/<Module>.lean`, unchanged, and writes

* `generated/qa2r/MANIFEST.sha256`: one line `sha256  Package/Module.lean` per source;
* `generated/qa2r/receipts.json`: for each source, the cache receipt key, the theorems the
  receipt names, and the recorded time and peak memory (used to schedule the build);
* `generated/qa2r/roots.txt`: the cited modules (the audit targets).

Nothing here is trusted: the sources are checked by `lake build` and
`scripts/check_axioms_qa2r.lean` (see `scripts/qa2r/replay.sh`).
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LAKE = ROOT / ".lake"
OUT = ROOT / "generated/qa2r"
SKIP = {"build", "packages", "config"}
IMPORT = re.compile(r"^(?:public )?(?:meta )?import (?:all )?([A-Za-z0-9_]+)\.([A-Za-z0-9_.]+)\s*$")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def imports(path):
    found, comment = [], False
    with open(path) as f:
        for line in f:
            t = line.strip()
            if comment:
                comment = "-/" not in t
                continue
            if t.startswith("/-"):
                comment = "-/" not in t
                continue
            m = IMPORT.match(t)
            if m:
                found.append((m[1], m[2]))
            elif t and t != "module" and not t.startswith("--"):
                if t.startswith(("import ", "public import ", "meta import ", "public meta import ")):
                    raise ValueError(f"unparsed import in {path}: {t}")
                break
    return found


def scan():
    """All generated sources: (package, module) -> list of (path, receipt or None)."""
    versions = {}
    for cache in sorted(LAKE.iterdir()):
        if cache.name in SKIP or not cache.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(cache):
            p = Path(dirpath)
            if p.name == "imports" and p.parent == cache:
                dirnames[:] = []
                continue
            leans = [f for f in filenames if f.endswith(".lean") and f != "Audit.lean"]
            if not leans:
                continue
            marker = p.parent / "accepted.json"
            receipt = json.loads(marker.read_text()) if marker.exists() else None
            for f in leans:
                versions.setdefault((p.name, f[:-5]), []).append((p / f, receipt))
    return versions


AUDIT = r"""import Lean.Util.CollectAxioms
import Lean.Data.Json
import CertifiedRadialSectorCache.DommaschkCertifiedRadialSector -- ROOT
/-! Axiom audit of the script-generated QA2R modules (`generated/qa2r/`, library `QA2RGenerated`).
Generated by `scripts/qa2r/collect_generated.py`.

Some cited modules belong to alternative versions of one computation and declare the same names,
so they cannot be imported together. `scripts/qa2r/replay.py` therefore runs this file once for
each module of `generated/qa2r/roots.txt`, replacing the import marked `ROOT`, and checks that
the runs together cover every source of the manifest. Run as it stands
(`lake env lean scripts/check_axioms_qa2r.lean`), it audits the sector theorem of N-205.

In one run: every visible declaration owned by an imported generated module (module root in
`generated/qa2r/packages.txt`) may depend only on `propext`, `Classical.choice` and `Quot.sound`,
(for a module imported indirectly these are its exported declarations, whose axiom sets,
recorded in the `.olean` file, include the axioms of the private declarations they use),
and every fully qualified theorem named by the campaign receipt of an imported module
(`generated/qa2r/receipts.json`) must exist. -/
open Lean Elab Command in
run_cmd do
  let env ← getEnv
  let allowed := #[``propext, ``Classical.choice, ``Quot.sound]
  let packages := (← IO.FS.lines "generated/qa2r/packages.txt").map (·.trimAscii.toString.toName)
  let mut count : NameMap Nat := {}
  for m in env.allImportedModuleNames do
    if packages.contains m.getRoot then count := count.insert m 0
  let mut checked : Nat := 0
  for (name, _) in env.constants.toList do
    if let some idx := env.getModuleIdxFor? name then
      let m := env.allImportedModuleNames[idx.toNat]!
      if let some n := count.find? m then
        -- For imported declarations the axiom sets are read from the `.olean` files.
        for ax in (← collectAxioms name) do
          unless allowed.contains ax do throwError "Unexpected axiom {ax} in {name}"
        count := count.insert m (n + 1)
        checked := checked + 1
  if checked == 0 then throwError "No generated declarations found: audit did not run"
  let json ← IO.ofExcept (Json.parse (← IO.FS.readFile "generated/qa2r/receipts.json"))
  let mut claimed : Nat := 0
  for (file, receipt) in (← IO.ofExcept json.getObj?).toList do
    let m := ((file.dropEnd 5).toString.replace "/" ".").toName
    if count.contains m then
      for t in (← IO.ofExcept ((receipt.getObjValD "theorems").getArr?)) do
        let s ← IO.ofExcept t.getStr?
        if s.startsWith "PlasmaLean." then
          unless env.contains s.toName do throwError "Receipt theorem {s} is missing"
          claimed := claimed + 1
  for (m, n) in count.toList do
    IO.println s!"module {m} {n}"
  IO.println s!"QA2R axiom audit passed: {checked} declarations in {count.size} generated \
    modules; {claimed} receipt theorems present."
"""

BEGIN, END = "# BEGIN QA2R generated (scripts/qa2r/collect_generated.py)", "# END QA2R generated"


def update_lakefile(packages):
    """Register the generated packages as roots of the on-demand library `QA2RGenerated`."""
    path = ROOT / "lakefile.toml"
    text = path.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip("\n") + "\n" + text[text.index(END) + len(END):].lstrip("\n")
    names = ", ".join(f'"{p}"' for p in packages)
    globs = ", ".join(f'"{p}.+"' for p in packages)
    block = f"""{BEGIN}
# Script-generated certificates of the QA2R campaign (notes N-49 onwards), not in the default
# build. Sources: `generated/qa2r/`. Build and audit: `scripts/qa2r/replay.sh`. The options
# restore Lean's defaults, under which the campaign compiled these files.
[[lean_lib]]
name = "QA2RGenerated"
srcDir = "generated/qa2r"
leanOptions = {{ relaxedAutoImplicit = true, maxSynthPendingDepth = 1, weak.linter.mathlibStandardSet = false, warningAsError = true }}
roots = [{names}]
globs = [{globs}]
{END}
"""
    path.write_text(text.rstrip("\n") + "\n\n" + block)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prefer", type=Path, action="append", default=[],
                        help="merged import root whose symlinks select among versions")
    parser.add_argument("--extra-root", action="append", default=[], help="further module names")
    args = parser.parse_args()
    versions = scan()
    preferred = set()
    for root in args.prefer:
        for link in root.glob("*/*.olean"):
            preferred.add(str(link.resolve())[:-6] + ".lean")
    choice, ambiguous = {}, []
    for key, items in versions.items():
        accepted = [x for x in items if x[1] is not None]
        linked = [x for x in items if str(x[0]) in preferred]
        pool = linked or accepted or items
        if len({sha(x[0]) for x in pool}) > 1:
            ambiguous.append("/".join(key))
        choice[key] = max(pool, key=lambda x: x[0].stat().st_mtime)
    text = subprocess.run(
        "cat notes/theory/*.md notes/audit/*.md notes/implementation-plan.md README.md "
        "progress/*.md progress/*.json docs/*.md", shell=True, cwd=ROOT, capture_output=True,
        text=True).stdout
    words = set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text)) | set(args.extra_root)
    committed = {p.stem for p in (ROOT / "PlasmaLean").rglob("*.lean")}
    # A cited name whose only source was never accepted by the campaign is not a root: it stays
    # out unless an accepted module imports it.
    roots = sorted(k for k in choice
                   if k[1] in words and k[1] not in committed and choice[k][1] is not None)
    rooted = {k[1] for k in roots}
    dropped = sorted({k[1] for k in choice
                      if k[1] in words and k[1] not in committed and k[1] not in rooted})
    seen, stack = set(), list(roots)
    while stack:
        key = stack.pop()
        if key in seen:
            continue
        seen.add(key)
        for pkg, mod in imports(choice[key][0]):
            if pkg in ("PlasmaLean", "Mathlib", "TauCeti", "Lean", "Std", "Init", "Batteries"):
                continue
            if (pkg, mod) not in choice:
                raise ValueError(f"{key}: import {pkg}.{mod} has no generated source")
            stack.append((pkg, mod))
    if OUT.exists():
        for child in OUT.iterdir():
            if child.is_dir():
                shutil.rmtree(child)
    OUT.mkdir(parents=True, exist_ok=True)
    manifest, receipts = [], {}
    for pkg, mod in sorted(seen):
        src, receipt = choice[(pkg, mod)]
        target = OUT / pkg / (mod + ".lean")
        target.parent.mkdir(exist_ok=True)
        shutil.copyfile(src, target)
        rel = f"{pkg}/{mod}.lean"
        manifest.append(f"{sha(target)}  {rel}")
        if receipt is not None:
            top = receipt.get("module") in (mod, None)
            receipts[rel] = {
                "key": receipt.get("key"), "top": top,
                "theorems": receipt.get("theorems", []) if top else [],
                "wall_seconds": receipt.get("wall_seconds"),
                "peak_rss_kib": receipt.get("peak_rss_kib")}
    (OUT / "MANIFEST.sha256").write_text("\n".join(manifest) + "\n")
    (OUT / "receipts.json").write_text(json.dumps(receipts, indent=0, sort_keys=True) + "\n")
    (OUT / "roots.txt").write_text("".join(f"{p}.{m}\n" for p, m in roots))
    (OUT / "packages.txt").write_text("".join(p + "\n" for p in sorted({k[0] for k in seen})))
    update_lakefile(sorted({k[0] for k in seen}))
    (ROOT / "scripts/check_axioms_qa2r.lean").write_text(AUDIT)
    unreceipted = [f"{p}/{m}" for p, m in sorted(seen) if choice[(p, m)][1] is None]
    in_closure = [a for a in ambiguous if tuple(a.split("/")) in seen]
    print(f"{len(roots)} cited modules, {len(seen)} sources, "
          f"{sum((OUT / l.split('  ')[1]).stat().st_size for l in manifest) / 1e6:.0f} MB")
    print(f"cited names with no accepted version in any package: {dropped}")
    print(f"{len(in_closure)} names with several distinct accepted versions (newest taken)")
    print(f"{len(unreceipted)} sources without a receipt: {unreceipted[:12]}")


if __name__ == "__main__":
    main()
