"""Reconstruct the 32 framed radial traces and export their dyadic slab records."""
import argparse
from concurrent.futures import ProcessPoolExecutor
from fractions import Fraction as F
import json
from math import ceil, floor
from pathlib import Path

import numpy as np

from bounce_common_section import common_section_inputs
import bounce_radial_tube as radial
from bounce_screen import load_inputs, seed_cut
from emit_radial_tiles import HERE, SCALE, SOURCES


def collect(job):
    section, height, tile_index, tile, output = job
    alpha, width, center = map(F, (tile['alpha_half_width'], tile['u_half_width'], tile['u_center']))
    inputs, transfer = common_section_inputs(alpha, width, center, section)
    data, seed, ev, initial = inputs
    v0, _ = radial.transfer_tangent(data, alpha, width, center, section, transfer)
    _, seeds = load_inputs()
    c, a = [seed_cut(*s, np.array([section*np.pi/2]))[0][:, 0] for s in seeds]
    for name, expected in zip(('back', 'fwd'), tile['runs'], strict=True):
        run_name = f's{section}h{height}p{tile_index}{name}'
        records = []

        def record(i, incoming, jump, final, defect, op, physical, mu, obs, oriented):
            # A tighter-than-necessary 128-bit upward rounding lets the kernel
            # check the very same outgoing 80-bit radius as the original trace.
            mu_scale = 1 << 128
            upper = ceil(max(F(0), mu)*mu_scale)
            e = int(defect*SCALE)
            assert e == defect*SCALE and op*(1 << 40) == int(op*(1 << 40))
            assert (incoming+jump)*64*mu_scale+e*mu_scale <= final*(64*mu_scale-upper)
            bounds = [n for key in ('B2', 'A2', 'B2_u', 'A2_u')
                      for n in (floor(obs[key][0]*SCALE), ceil(obs[key][1]*SCALE))]
            # Categorize by the undiminished *rounded* bounds to ensure that
            # a slab skipped for the orientation check excludes both heights.
            flag = (-1 if F(bounds[1], SCALE) < radial.pilot.HEIGHTS[0]**2 else
                    1 if radial.pilot.HEIGHTS[1]**2 < F(bounds[0], SCALE) else 0)
            if flag == 0 and oriented is None:
                raise ArithmeticError('outward rounding acquired a mirror-band overlap')
            slope = floor(oriented[0]*SCALE) if oriented is not None else 0
            records.append([i, incoming, jump, final, e, int(op*(1 << 40)), physical, upper,
                            *bounds, flag, slope])

        result = radial.directed(data, seed, ev, initial, v0, a-c, expected['direction'],
                                 F(tile['step']), F(tile['limit']), F(0), True, record=record)
        if result != expected:
            diffs = [key for key in result if result[key] != expected[key]]
            raise ValueError(f'{run_name} differs from archived trace in {diffs}')
        (output/f'{run_name}.json').write_text(json.dumps(records, separators=(',', ':')))
        print(run_name, len(records), flush=True)


def packet(row):
    _, _, jump, final, defect, op, error, mu, bl, bh, al, ah, db0, db1, da0, da1, _, slope = row
    fields = (jump, final, defect, op, error, bl, bh, al, ah, -db1, -db0, da0, da1, slope)
    if not all(0 <= x < 1 << 96 for x in fields) or not 0 <= mu < 1 << 128:
        raise ArithmeticError('invalid signed field or overflowing slab digit')
    return sum(x << (96*i) for i, x in enumerate(fields)) + (mu << 1344)


