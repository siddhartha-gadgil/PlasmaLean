"""Produce exact principal-minor certificates for closed panels of a stored Jacobian."""
import argparse
from fractions import Fraction as F

from bounce_mirror_pilot import Model, ORDER, SCALE
from emit_sparse_taylor_slab import DEST, RECORD, model_literal
from screen_sparse_jacobians import jobs, symmetric_models
from screen_sparse_reference_defects import bounds


def emit(index):
    sec,sign,_,start,step,panels,_ = next(j for j in jobs(RECORD,8,False,1) if j[1:3] == (1,index))
    coordinates = (Model(a,step['physical_trial_radius']) for a in step['coefficients'])
    models = symmetric_models(sec,sign,index,start,step,*coordinates)
    name = f'DommaschkJacobianForward{index:03}Panels'
    out = f'''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkJacobianPanels

/-! # Normalized-time panel certificate for forward slab {index}

Generated by `scripts/dommaschk_kam/emit_sparse_jacobian_panels.py`.
-/

@[expose] public section
namespace PlasmaLean.Design.{name}
open DommaschkJacobian Certificates.TrajectoryTaylorModel

set_option linter.style.longLine false
set_option Elab.async false

/-- The common denominator, diagonal numerators and symmetric off-diagonal sum. -/
def models : SymmetricModels := ⟨'''+',\n  '.join(map(model_literal,models))+'⟩\n\n'
    mu = F(step['log_norm_upper'])
    out += f'def budget : ℚ := {mu}\n\n'
    def rat(x): return '('+str(x)+')'
    leaves = []
    for i, (bd,aa,dd,bc) in enumerate(zip(*(bounds(model,panels) for model in models),strict=True)):
        denom = SCALE*panels**ORDER
        dl,a,d,w = (F(x,denom) for x in (bd[0],aa[1],dd[1],max(map(abs,bc))))
        if min(mu*dl-a,mu*dl-d)<0 or w*w>4*(mu*dl-a)*(mu*dl-d):
            raise ValueError(f'spatial refinement required on panel {i}')
        left,right = map(rat,(F(2*i-panels,panels),F(2*i+2-panels,panels)))
        out += f'''private theorem panel{i} : MinorCover models budget {left} {right} := by
  apply MinorCover.panel
  refine ⟨{dl}, {a}, {d}, {w}, ?_, ?_, ?_, ?_, ?_, ?_, ?_, ?_, ?_, ?_⟩ <;> kernel_fact

'''
        leaves.append('panel'+str(i))
    while len(leaves)>1:
        leaves=['(MinorCover.join '+leaves[i]+' '+leaves[i+1]+')' for i in range(0,len(leaves),2)]
    out += f'''/-- The eight rational panels cover the entire normalized slab. -/
theorem accepted : MinorCover models budget (-1) 1 := {leaves[0]}

/-- Every matrix in the four simultaneous model enclosures satisfies the archived
quadratic bound at every intermediate time. -/
theorem bounded {{t den : ℝ}} {{A : Entries}} (ht : |t| ≤ 1) (h : models.Mem t den A) :
    0 < den ∧ ∀ x y : ℝ, A.quad x y / den ≤ (budget : ℝ) * (x ^ 2 + y ^ 2) := by
  apply accepted.sound _ h
  simpa only [Set.mem_Icc, Rat.cast_neg, Rat.cast_one] using abs_le.mp ht

end PlasmaLean.Design.{name}
'''
    return name,out


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--index',type=int,default=42,choices=range(391),metavar='0..390')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    name,source=emit(args.index)
    p=DEST/(name+'.lean')
    if args.check:
        if p.read_text() != source:
            raise SystemExit('regenerate '+p.name)
    else:
        p.write_text(source)
