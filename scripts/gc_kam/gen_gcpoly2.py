"""UNTRUSTED generator of PlasmaLean/Design/RationalStellaratorGCPoly2.lean: second partial
derivatives of the field polynomials D, n_R, n_z and the derivative of P (for the u/z-derivatives of
the guiding-centre field in the torsion of the KAM step).  Every identity is checked by `ring`."""
import sys
import sympy as sp
sys.path.insert(0, '/Users/gadgil/code/PlasmaLean/scripts/gc_kam')
from gcmodel import BASE, ALLP, u, z, c, s
from gen_gcflow import lean_rat, HDR

OUT = '/Users/gadgil/code/PlasmaLean/PlasmaLean/Design/'


def phiP(e):
    return sp.expand(sp.diff(e, c) * (-2 * s) + sp.diff(e, s) * (2 * c))


def emit_poly(name, expr, doc):
    P = sp.Poly(expr, u, z, c, s)
    terms = sorted(P.terms(), key=lambda t: (-sum(t[0]), t[0]))
    lines = []
    for (i, j, k, l), co in terms:
        mono = ['(%d, %d)' % (idx, e) for idx, e in enumerate((i, j, k, l)) if e]
        lines.append('    monoE %s [%s]' % (lean_rat(co), ', '.join(mono)))
    if not lines:
        lines = ['    monoE (0) []']
    return '/-- %s -/\ndef %s : PolyExpr ℂ (Fin 6) := sumE [\n%s]\n' % (doc, name, ',\n'.join(lines))


NEW = {}
DOC = {}
NEW['PdP'] = sp.expand(sp.diff(ALLP['PuP'], u))
DOC['PdP'] = '`∂_u P` (derivative of the Taylor polynomial of `R^{−3}`).'
for b, lb in [('D', 'D'), ('nR', 'n_R'), ('nZ', 'n_z')]:
    X0 = BASE[b + 'p']
    NEW[b + 'uuP'] = sp.expand(sp.diff(X0, u, 2)); DOC[b + 'uuP'] = '`∂_u² %s`.' % lb
    NEW[b + 'uzP'] = sp.expand(sp.diff(X0, u, z)); DOC[b + 'uzP'] = '`∂_u∂_z %s`.' % lb
    NEW[b + 'zzP'] = sp.expand(sp.diff(X0, z, 2)); DOC[b + 'zzP'] = '`∂_z² %s`.' % lb
    NEW[b + 'uphP'] = sp.expand(sp.diff(phiP(X0), u)); DOC[b + 'uphP'] = '`∂_u∂_φ %s`.' % lb
    NEW[b + 'zphP'] = sp.expand(sp.diff(phiP(X0), z)); DOC[b + 'zphP'] = '`∂_z∂_φ %s`.' % lb
names = list(NEW)
out = [HDR, """
public import PlasmaLean.Design.RationalStellaratorGCPoly

/-!
# Second derivatives of the field polynomials of the guiding-centre field (generated)

The `u`- and `z`-derivatives of the guiding-centre field `B̃ = B + ρ ∇×b`
(`Design/RationalStellaratorGCFlow`) involve the second partial derivatives of the field
polynomials `D, n_R, n_z` of `Design/KamNewtonField` (in `u, z` and mixed with `φ`) and the
derivative of the Taylor polynomial `P(u)` of `R^{−3}`. This file gives them as polynomial
expressions with their identities (`pd x i X = eval x Y`, checked pointwise by `ring`); they are
used in the ball certificate of the torsion (`Design/RationalStellaratorGCTorusRelL`). Generated by
`scripts/gc_kam/gen_gcpoly2.py` (untrusted).

**Sanity.** `PdP_zero`: `P'(0) = −3`.
-/

@[expose] public section
noncomputable section

namespace PlasmaLean.Design.RationalStellaratorGC

open PlasmaLean.Theory.KAM PlasmaLean.Design.KamNewton PolyExpr Complex WEll1Z2

"""]
for n in names:
    out.append(emit_poly(n, NEW[n], DOC[n]))
    out.append('')
out.append("""/-- Unfolding set for the polynomials of this file, `Design/RationalStellaratorGCPoly` and
`Design/KamNewtonField`. -/
macro "gc2_poly_simp" : tactic =>
  `(tactic| simp only [phiD, pd, PolyExpr.deriv, PolyExpr.eval, KamNewton.Dp, KamNewton.nRp,
    KamNewton.nZp, DuP, DzP, DphP, nRuP, nRzP, nRphP, nZuP, nZzP, nZphP, PuP,
    %s,
    sumE, monoE, npow, Pi.single_apply, Algebra.algebraMap_self, RingHom.id_apply,
    Fin.isValue, eval_npow])

/-- Close a polynomial identity pointwise. -/
macro "gc2_close" : tactic =>
  `(tactic| (refine ext_eval fun θ ψ => ?_
             simp only [eval_add', eval_sub', eval_mul, eval_neg', eval_pow', eval_pd, eval_phiD,
               eval_polyExpr, eval_one, eval_ofNat', eval_zero']
             gc2_poly_simp
             all_goals (try simp)
             all_goals ring))

""" % ',\n    '.join([', '.join(names[:8]), ', '.join(names[8:])]))
rel = [('Pd_d0', 'pd x 0 PuP', 'PdP')]
for b in ['D', 'nR', 'nZ']:
    rel += [(b + '_uu', 'pd x 0 %suP' % b, b + 'uuP'), (b + '_uz', 'pd x 1 %suP' % b, b + 'uzP'),
            (b + '_zu', 'pd x 0 %szP' % b, b + 'uzP'), (b + '_zz', 'pd x 1 %szP' % b, b + 'zzP'),
            (b + '_phu', 'pd x 0 %sphP' % b, b + 'uphP'), (b + '_phz', 'pd x 1 %sphP' % b, b + 'zphP')]
for nm, lhs, rhs in rel:
    out.append('/-- `%s = %s`. -/\ntheorem %s (x : Fin 6 → FA) :\n    %s = PolyExpr.eval x %s := by\n  gc2_close\n\n'
               % (lhs.replace('x ', ''), rhs, nm, lhs, rhs))
out.append("""/-- Sanity: `P'(0) = −3`. -/
theorem PdP_zero : PolyExpr.eval (A := ℂ) (fun _ => 0) PdP = -3 := by
  gc2_poly_simp; norm_num

end PlasmaLean.Design.RationalStellaratorGC
""")
open(OUT + 'RationalStellaratorGCPoly2.lean', 'w').write('\n'.join(out))
print('ok', names)
