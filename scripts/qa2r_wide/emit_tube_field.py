"""Emit the field-bound certificates on the tube around the QA2R label-0.474 field line.

For each of the first 224 forward slabs the Boolean check `fine g s b c m` of
`PlasmaLean/Design/DommaschkGradientCheck.lean` is applied to the box
`DommaschkTubeField.slabBox row nc ns` of the slab (the coordinate rectangle of the trial tube and
the arc of (cos 2 phi, sin 2 phi); both are Lean definitions, so no number of the box is produced
here). The check is first evaluated with Lean's own evaluator (`#eval`, untrusted), which also
searches the box-local lower bound `β` of the toroidal component, halving the box in u where the
check fails; the resulting trees are stored in `results/tube_field_trees.json`. Then
28 modules `WideTube/DommaschkWideTubeRows000FieldNN.lean` (8 slabs each, every leaf one theorem
`fine ... = true` closed by `kernel_fact`) and the assembly
`WideTube/DommaschkWideTubeRows000Field.lean` are written to `generated/qa2r_wide/`.

Because the scan uses the Lean definitions of the certificate, no rounding convention is
duplicated here. The only numbers read by the scan are the centre numerators of the harmonic
packets, parsed from `PlasmaLean/Design/DommaschkHarmonicBlockNN.lean`; the emitted modules refer
to the packets themselves, so a parsing mistake can only make a kernel check fail.

    python3 scripts/qa2r_wide/emit_tube_field.py            # scan and emit
    python3 scripts/qa2r_wide/emit_tube_field.py --reuse    # emit from the stored trees
    python3 scripts/qa2r_wide/emit_tube_field.py --check    # compare emitted files with the trees

Build (about 40 s and 12 GB per leaf, one Lean process per module):

    lake build WideTube.DommaschkWideTubeRows000Field
"""
import argparse
import json
import re
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "PlasmaLean" / "Design"
OUT = ROOT / "generated" / "qa2r_wide" / "WideTube"
TREES = Path(__file__).resolve().parent / "results" / "tube_field_trees.json"
SLABS = 224
GROUP = 8
DEPTH = 3
# Thresholds: gradient of |B|, |B| from below, B_phi from below and above, planar speed.
G, S, BLO, BHI, M = "(11 / 8)", "(1039 / 1000)", "(103 / 100)", "(21 / 20)", "(7 / 50)"
THRESHOLDS = f"{G} {S} {BLO} {BHI} {M}"
PREFIX = "DommaschkWideTubeRows000Field"

SCAN = '''import PlasmaLean.Design.DommaschkTubeField
import WideTube.DommaschkWideTubeRows000
open PlasmaLean PlasmaLean.Design PlasmaLean.Design.DommaschkBounceField
open PlasmaLean.Design.DommaschkGradientCheck PlasmaLean.Design.DommaschkTubeField
open PlasmaLean.Design.DommaschkRegionGrid
open PlasmaLean.Design.DommaschkRegionEnclosure
def bsearch (f : ℚ → Bool) (lo hi : ℚ) : Nat → ℚ
  | 0 => lo
  | n + 1 => let mid := (lo + hi) / 2; if f mid then bsearch f mid hi n else bsearch f lo mid n
/-- The largest lower bound of the toroidal component on the box, on a dyadic grid. -/
def beta (B : Box) : ℚ := bsearch (fun b => good b BHI M B) BLO (BLO + 1 / 16) 14
def leaf (B : Box) : Option String :=
  let β := beta B
  if fine THRESHOLDS β B then some s!"L[{β.num}/{β.den}]" else none
def tree : Nat → Box → String
  | 0, B => (leaf B).getD "F"
  | d + 1, B => (leaf B).getD
      ("H" ++ tree d ⟨lower B.u, B.z, B.c, B.s⟩ ++ tree d ⟨upper B.u, B.z, B.c, B.s⟩)
#eval [BOXES].map (tree DEPTH)
'''

HEAD = '''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

{imports}

/-! # {title}

Generated by `scripts/qa2r_wide/emit_tube_field.py`. {text} -/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{name}

'''


def numerators(k):
    """Centre numerators of cos and sin of (2k+1)/64, from the harmonic packet of slab k."""
    text = (DESIGN / f"DommaschkHarmonicBlock{k // GROUP:02d}.lean").read_text()
    found = re.search(rf"\| {k % GROUP}, false, 0 =>\s*⟨⟨(-?\d+), \d+, by kernel_fact⟩,\s*"
                      r"⟨(-?\d+), \d+, by kernel_fact⟩", text)
    if not found:
        raise ValueError(f"no harmonic packet for slab {k}")
    return int(found.group(1)), int(found.group(2))


def scan_group(n):
    boxes = []
    for k in range(GROUP * n, GROUP * (n + 1)):
        nc, ns = numerators(k)
        boxes.append(f"slabBox DommaschkWideTubeRows000.row{k} ({nc}) ({ns})")
    text = (SCAN.replace("THRESHOLDS", THRESHOLDS).replace("DEPTH", str(DEPTH))
            .replace("BLO", BLO).replace("BHI", BHI).replace(" M B", f" {M} B")
            .replace("BOXES", ",\n  ".join(boxes)))
    with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False) as handle:
        handle.write(text)
    out = subprocess.run(["lake", "env", "lean", handle.name], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout
    Path(handle.name).unlink()
    trees = re.findall(r'"([LHF0-9/\[\]]+)"', out)
    if len(trees) != GROUP:
        raise ValueError(f"scan of group {n}: unexpected output\n{out}")
    return {str(GROUP * n + j): t for j, t in enumerate(trees)}


def scan():
    trees = {}
    with ThreadPoolExecutor(max_workers=14) as pool:
        for part in pool.map(scan_group, range(SLABS // GROUP)):
            trees.update(part)
    return trees


def parse(tree, pos=0, path=()):
    """Return (structure, next position); a structure is a leaf (path, beta) or a pair of
    structures."""
    if tree[pos] == "L":
        end = tree.index("]", pos)
        return (path, tree[pos + 2:end]), end + 1
    if tree[pos] != "H":
        raise ValueError("the check fails at the maximal depth")
    left, pos = parse(tree, pos + 1, path + ("lower",))
    right, pos = parse(tree, pos, path + ("upper",))
    return [left, right], pos


def box(k, path):
    expr = f"box{k}"
    for depth, half in enumerate(path):
        if depth:
            expr = f"{expr} : Box"
        expr = f"⟨{half} ({expr}).u, ({expr}).z, ({expr}).c, ({expr}).s⟩"
    return expr


def emit_slab(k, tree):
    structure, end = parse(tree)
    if end != len(tree):
        raise ValueError(f"malformed tree for slab {k}")
    block, j = f"DommaschkHarmonicBlock{k // GROUP:02d}", k % GROUP
    lines = [f"/-- The box of slab {k}. -/\n"
             f"abbrev box{k} : Box := slabBox row{k} ({block}.packet {j} false 0).cosCentre.numerator\n"
             f"  ({block}.packet {j} false 0).sinCentre.numerator"]
    counter = [0]

    def term(node):
        if isinstance(node, tuple):
            path, beta = node
            name = f"leaf{k}_{counter[0]}"
            counter[0] += 1
            lines.append(f"private theorem {name} :\n    fine {THRESHOLDS} ({beta}) {box(k, path)} = true := by\n"
                         "  kernel_fact")
            return f".leaf ({beta}) {name}"
        return ".halves " + " ".join(f"({term(child)})" for child in node)

    body = term(structure)
    lines.append(f"/-- The polynomial inequalities on the trial tube of slab {k}. -/\n"
                 f"theorem slab{k} : SlabQ {THRESHOLDS} {k} row{k} :=\n"
                 f"  slabQ_of_cert ({block}.packet {j}) rfl (by norm_num) (by norm_num)\n    ({body})")
    return "\n\n".join(lines) + "\n"


def generate(trees):
    files = {}
    groups = SLABS // GROUP
    for n in range(groups):
        ks = range(GROUP * n, GROUP * (n + 1))
        imports = ("public import PlasmaLean.Design.DommaschkTubeField\n"
                   f"public import PlasmaLean.Design.DommaschkHarmonicBlock{n:02d}\n"
                   "public import WideTube.DommaschkWideTubeRows000")
        name = f"{PREFIX}{n:02d}"
        text = HEAD.format(imports=imports, name=name,
                           title=f"Field bounds on the trial tubes of forward slabs {ks[0]}–{ks[-1]}, label 0.474",
                           text="Every leaf is one evaluation of the box check\n"
                                "`DommaschkGradientCheck.fine` by the kernel.")
        text += ("open DommaschkBounceField DommaschkGradientCheck DommaschkTubeField DommaschkRegionGrid\n"
                 "open DommaschkWideTubeRows000\n\n"
                 "set_option linter.style.longLine false\nset_option maxRecDepth 100000\n\n")
        text += "\n".join(emit_slab(k, trees[str(k)]) for k in ks)
        rows = ", ".join(f"row{k}" for k in ks)
        slabs = ", ".join(f"slab{k}" for k in ks)
        text += (f"\n/-- The polynomial inequalities along the slabs {ks[0]}–{ks[-1]}. -/\n"
                 f"theorem slabs : SlabsOn (SlabQ {THRESHOLDS}) {ks[0]}\n    [{rows}] :=\n"
                 f"  ⟨{slabs}, trivial⟩\n\nend PlasmaLean.Design.{name}\n")
        files[f"{name}.lean"] = text
    imports = "public import WideTube.DommaschkWideTubeRows000Tube\n" + "\n".join(
        f"public import WideTube.{PREFIX}{n:02d}" for n in range(groups))
    text = HEAD.format(imports=imports, name=PREFIX,
                       title="Field bounds on the two-sided tube around forward slabs 0–223, label 0.474",
                       text="The thresholds are those of the\nper-slab modules: gradient of the "
                            "field strength, strength, toroidal component, planar speed.")
    text += ASSEMBLY.replace("THRESHOLDS", THRESHOLDS)
    for n in range(groups):
        if n == 0:
            text += (f"private theorem slabsTo0 : SlabsOn (SlabQ {THRESHOLDS}) 0 DommaschkWideTubeRows000Joined.all0 :=\n"
                     f"  {PREFIX}00.slabs\n\n")
        else:
            text += (f"private theorem slabsTo{n} : SlabsOn (SlabQ {THRESHOLDS}) 0 DommaschkWideTubeRows000Joined.all{n} :=\n"
                     f"  slabsTo{n - 1}.append (by rw [DommaschkWideTubeRows000Joined.length{n - 1}]; exact {PREFIX}{n:02d}.slabs)\n\n")
    text += FINAL.replace("LAST", str(groups - 1)).replace("THRESHOLDS", THRESHOLDS)
    text += f"\nend PlasmaLean.Design.{PREFIX}\n"
    files[f"{PREFIX}.lean"] = text
    return files


ASSEMBLY = '''open Certificates PositionFrameSlabs PositionFrameTube DommaschkJacobian DommaschkTubeSymmetry
open DommaschkSignedTraceDomain DommaschkGradientCheck DommaschkTubeField DommaschkRegionFieldBounds
open DommaschkCartesianAngleFlow DommaschkWideTubeRows000Tube Contract Fields Set

set_option linter.style.longLine false

'''

FINAL = '''/-- The polynomial inequalities on the trial tube of every slab of the chain. -/
theorem slabs : SlabsOn (SlabQ THRESHOLDS) 0 rows := slabsToLAST

/-- The two-sided trial tube around the first 224 slabs. -/
abbrev W : ℝ → Set Plane := FlowLabel.doubleW flipIso 0 (outer DommaschkWideTubeRows000.start 0 rows)

/-- The two-sided tube lies in the cylindrical envelope. -/
theorem region_of_double {t : ℝ} {x : Plane} (hx : x ∈ W t) : Region x := by
  rcases double_cases hx with h | ⟨y, hy, rfl⟩
  · exact region_of_outer h
  · exact region_flip (region_of_outer hy)

/-- **All bounds at once**, with `PolyBounds` for the toroidal and poloidal components. -/
theorem bounds {t : ℝ} {x : Plane} (hx : x ∈ W t) :
    ‖Kinetic.GCLittlejohn.gradAbsB B (cylPoint (x 0) t (x 1))‖ ≤ 11 / 8 ∧
      1039 / 1000 ≤ ‖B (cylPoint (x 0) t (x 1))‖ ∧ ‖euclideanFlow 0 1 t x‖ ≤ 7 / 50 ∧
      PolyBounds (103 / 100) (21 / 20) (7 / 50) (x 0) t (x 1) := by
  have h := field_of_double geo slabs (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (fun _ _ hy => by linarith [(region_of_outer hy).1.1]) hx
  norm_num at h
  exact h

/-- **Gradient of the field strength**: at most `11/8` on the two-sided tube, at every angle. -/
theorem gradAbsB_le {t : ℝ} {x : Plane} (hx : x ∈ W t) :
    ‖Kinetic.GCLittlejohn.gradAbsB B (cylPoint (x 0) t (x 1))‖ ≤ 11 / 8 := (bounds hx).1

/-- **Field strength from below**: at least `1039/1000` on the two-sided tube. -/
theorem strength_ge {t : ℝ} {x : Plane} (hx : x ∈ W t) :
    1039 / 1000 ≤ ‖B (cylPoint (x 0) t (x 1))‖ := (bounds hx).2.1

/-- **Planar speed** of the field-line equation: at most `7/50` on the two-sided tube. -/
theorem speed_le {t : ℝ} {x : Plane} (hx : x ∈ W t) : ‖euclideanFlow 0 1 t x‖ ≤ 7 / 50 :=
  (bounds hx).2.2.1

/-- The toroidal component lies between `103/100` and `21/20` on the two-sided tube. -/
theorem toroidal_bounds {t : ℝ} {x : Plane} (hx : x ∈ W t) :
    103 / 100 ≤ DommaschkKam.cylBphi (x 0) t (x 1) ∧ DommaschkKam.cylBphi (x 0) t (x 1) ≤ 21 / 20 :=
  (bounds hx).2.2.2.toroidal (by linarith [(region_of_double hx).1.1])

set_option maxRecDepth 8000 in
/-- **Field strength from above**: at most `107/100` on the two-sided tube. -/
theorem strength_le {t : ℝ} {x : Plane} (hx : x ∈ W t) :
    ‖B (cylPoint (x 0) t (x 1))‖ ≤ 107 / 100 := by
  have reg := region_of_double hx
  have hR : 0 < x 0 := by linarith [reg.1.1]
  have sq := (bounds hx).2.2.2.strength_sq_le hR (by norm_num)
  apply (sq_le_sq₀ (norm_nonneg _) (by norm_num)).mp
  refine sq.trans ?_
  have r2 : (7 / 8 : ℝ) ^ 2 ≤ x 0 ^ 2 := pow_le_pow_left₀ (by norm_num) reg.1.1 2
  have inv : (7 / 50 : ℝ) ^ 2 / x 0 ^ 2 ≤ (7 / 50) ^ 2 / (7 / 8) ^ 2 :=
    div_le_div_of_nonneg_left (by norm_num) (by norm_num) r2
  nlinarith

/-- The speed bound in the form of the field `speed` of `FlowLabel.Tube`, on any time
interval. -/
theorem flowLabel_speed_le (a b : ℝ) : ∀ t ∈ Ioo a b, ∀ x ∈ W t, ‖euclideanFlow 0 1 t x‖ ≤ 7 / 50 :=
  fun _ _ _ hx => speed_le hx

/-- **Sanity**: the bounds are not vacuous: the reference point of the first slab at angle zero
lies in the two-sided tube. -/
theorem nonempty : (W 0).Nonempty := by
  refine ⟨reference (time 0 0) (rowAt rows 0) 0, ?_⟩
  rw [W, FlowLabel.doubleW_self]
  refine Or.inl ⟨0, positive, ?_, ?_⟩
  · rw [time_succ, time_zero]
    exact ⟨le_rfl, by norm_num⟩
  · change ‖(frameAt DommaschkWideTubeRows000.start 0 rows 0 0).symm
      (reference (time 0 0) (rowAt rows 0) 0 - reference (time 0 0) (rowAt rows 0) 0)‖ ≤ _
    rw [sub_self, map_zero, norm_zero]
    positivity
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reuse", action="store_true", help="use the stored trees")
    parser.add_argument("--check", action="store_true", help="compare with the emitted files")
    args = parser.parse_args()
    if args.reuse or args.check:
        trees = json.loads(TREES.read_text())
    else:
        trees = scan()
        TREES.parent.mkdir(exist_ok=True)
        TREES.write_text(json.dumps(trees, indent=0, sort_keys=True) + "\n")
    if any("F" in t for t in trees.values()):
        raise SystemExit("the check fails at the maximal depth on some slab: "
                         + ", ".join(k for k, t in trees.items() if "F" in t))
    files = generate(trees)
    leaves = sum(t.count("L") for t in trees.values())
    if set(trees) != {str(k) for k in range(SLABS)}:
        raise SystemExit("the stored trees do not cover the slabs")
    print(f"{len(trees)} slabs, {leaves} leaves, {len(files)} files")
    for name, text in files.items():
        if args.check:
            if (OUT / name).read_text() != text:
                raise SystemExit(f"{name} differs from regeneration")
        elif not (OUT / name).exists() or (OUT / name).read_text() != text:
            (OUT / name).write_text(text)


if __name__ == "__main__":
    main()
