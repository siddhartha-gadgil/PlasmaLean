def emit(folder, check):
    for section, source in enumerate(SOURCES):
        spec = json.loads((HERE/'results'/source).read_text())
        for height, bracket in enumerate(spec['brackets']):
            name = f'DommaschkRadialSlabsS{section}H{height}'
            lines = [header(name)]
            for i, tile in enumerate(bracket['tiles']):
                for direction, half in zip(('back','fwd'), tile['runs'], strict=True):
                    tag = f's{section}h{height}p{i}{direction}'
                    b = half['bounds']
                    env = [*b['B2'], *b['A2'], -b['B2_u'][1], -b['B2_u'][0], *b['A2_u']]
                    extra = [half[k] for k in ('core_B2_upper_numerator','end_B2_lower_numerator',
                             'outward_B2_slope_lower_numerator','max_tangent_defect_numerator',
                             'max_tangent_error_numerator')]
                    rows = json.loads((folder/f'{tag}.json').read_text())
                    if len(rows) != 391 or any(a[3] != b[1] for a,b in zip(rows,rows[1:])):
                        raise ArithmeticError('missing slab or incoming radius mismatch')
                    chunks = [rows[j:j+12] for j in range(0,len(rows),12)]
                    lines.extend([f'/-- Dyadic extrema for the directed trace `{tag}`. -/',
                                  f'def {tag}Env : Envelope :=',
                                  '  ⟨⟨'+', '.join(map(str,env))+'⟩, '+', '.join(map(str,extra))+'⟩','',
                                  '/-- These are exactly the extrema consumed by the real action theorem. -/',
                                  f'theorem {tag}_matches : {tag}Env.Matches {tag} := by',
                                  f'  norm_num [Envelope.Matches, {tag}Env, {tag}, dyadic]','',
                                  '/-- Consecutive blocks of 1/64-radian slab records. -/',
                                  f'def {tag}Blocks : List (ℕ × ℕ) := ['])
                    for j,chunk in enumerate(chunks):
                        p = sum(packet(row) << (1472*k) for k,row in enumerate(chunk))
                        lines.append(f'  ({len(chunk)}, 0x{p:x})'+(']' if j+1==len(chunks) else ','))
                    lines.extend(['', '/-- Kernel replay of the complete ordered tangent and observable record. -/',
                                  f'theorem {tag}_checked : Chain {tag}Env 0 {rows[0][1]} 391',
                                  f'    {rows[-1][3]} {tag}Blocks := by',f'  unfold {tag}Blocks'])
                    for chunk in chunks:
                        lines.extend([f'  refine Chain.cons _ _ _ _ {chunk[-1][3]} ?_ ?_', '  · rfl'])
                    lines.extend(['  exact .nil _ _',''])
            lines.append(f'end PlasmaLean.Design.{name}')
            text = '\n'.join(lines)+'\n'
            path = HERE.parents[1]/'PlasmaLean'/'Design'/f'{name}.lean'
            if check:
                if path.read_text() != text:
                    raise ValueError(f'{path.name} differs from rebuilt slabs')
            else:
                path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('--workers', type=int, default=4)
    parser.add_argument('--use-records', action='store_true', help='reuse already reconstructed JSON slabs')
    parser.add_argument('--check', action='store_true', help='compare the emitted Lean proofs')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    jobs = [(section, height, i, tile, args.output)
            for section, name in enumerate(SOURCES)
            for height, bracket in enumerate(json.loads((HERE/'results'/name).read_text())['brackets'])
            for i, tile in enumerate(bracket['tiles'])]
    if not args.use_records:
        with ProcessPoolExecutor(max_workers=args.workers) as pool:
            list(pool.map(collect, jobs))
    emit(args.output, args.check)


if __name__ == '__main__':
    main()
