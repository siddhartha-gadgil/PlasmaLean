"""Compute the three exact uniform polynomial perturbation budgets for the section-zero tubes."""
import argparse
from fractions import Fraction as F
from math import ceil

from bounce_mirror_pilot import SCALE
from emit_sparse_taylor_slab import DEST
from screen_sparse_reference_defects import sparse_fields


U,Z,E=F(3,32),F(5,64),F(1,2**18)


def budget(terms):
    total=sum(abs(q)*((U+E)**a*(Z+E)**b-U**a*Z**b) for q,(a,b,_,_) in terms)
    return ceil(SCALE*total)


def render():
    src='''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkPhysicalPolynomialError

/-! # Uniform spatial error budgets for the three QA2R field polynomials

Generated by `scripts/dommaschk_kam/emit_uniform_field_error.py`.
-/

@[expose] public section
namespace PlasmaLean.Design.DommaschkUniformFieldError
open DommaschkKam DommaschkKamC
set_option maxRecDepth 16000
'''
    for p,t in zip(('dD','dnR','dnZ'),sparse_fields(),strict=True):
        src+=f'''
/-- Upward-rounded change in {p} when both physical coordinates move by at most 2⁻¹⁸. -/
def {p}Budget : ℚ := {budget(t)} / 2 ^ 80

theorem {p}_bound : lipQ (3/32) (5/64) (1/2^18) (1/2^18) 1 {p} ≤ {p}Budget := by
  kernel_fact
'''
    return src+'\nend PlasmaLean.Design.DommaschkUniformFieldError\n'


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    args=p.parse_args()
    path=DEST/'DommaschkUniformFieldError.lean'
    data=render()
    if args.check:
        if path.read_text()!=data:
            raise SystemExit('regenerate '+str(path))
    else:
        path.write_text(data)
