def wrap_comments(s, width=100):
    """Break comment lines longer than `width` characters at a space outside code spans."""
    out, inc = [], False
    for line in s.split('\n'):
        starts = '/-' in line
        if (inc or starts) and len(line) > width:
            rest = line
            while len(rest) > width:
                k, tick = -1, 0
                for i, ch in enumerate(rest[:width + 1]):
                    if ch == '`':
                        tick ^= 1
                    elif ch == ' ' and not tick and i > 10:
                        k = i
                if k < 0:
                    break
                out.append(rest[:k])
                ind = '  ' if rest.lstrip().startswith('* ') else ''
                rest = ind + rest[k + 1:]
            out.append(rest)
        else:
            out.append(line)
        for tok in re.findall(r'/-|-/', line):
            inc = tok == '/-'
    return '\n'.join(out)


