"""Emit the subdivision certificates of `PlasmaLean/Design/DommaschkRegionGrid.lean`.

For every cell `cell i j f m` of the grid (4 x 2 x 8 x 12 boxes of the QA2R envelope and the
unit circle of (cos 2 phi, sin 2 phi)) the Boolean check `good` of
`PlasmaLean/Design/DommaschkRegionEnclosure.lean` is evaluated with Lean's own evaluator
(`#eval`, untrusted), subdividing in (u, z) where it fails. The resulting trees are written to
`results/region_trees.json`, and Lean modules are emitted in which every leaf is one theorem
`good ... = true` closed by `kernel_fact` (the kernel evaluates the interval arithmetic), and
every cell has a term of type `Cert (cell i j f m)`.

Because the search uses the same Lean definitions as the certificate, no rounding convention is
duplicated here; a tree with a failing leaf at the maximal depth aborts the emission.

    python scripts/qa2r_wide/emit_region_rows.py            # scan and emit
    python scripts/qa2r_wide/emit_region_rows.py --reuse    # emit from the stored trees
    python scripts/qa2r_wide/emit_region_rows.py --check    # compare emitted files with the tree
"""
import argparse
import json
import re
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "PlasmaLean" / "Design"
TREES = Path(__file__).resolve().parent / "results" / "region_trees.json"
NI, NJ, NF, NM = 4, 2, 8, 12
DEPTH = 4
FILES = 24

SCAN = '''import PlasmaLean.Design.DommaschkRegionGrid
open PlasmaLean.Design PlasmaLean.Design.DommaschkBounceField
open PlasmaLean.Design.DommaschkRegionEnclosure PlasmaLean.Design.DommaschkRegionGrid
def tree : Nat → Box → String
  | 0, B => if good b₀ c₁ M B then "L" else "F"
  | d + 1, B => if good b₀ c₁ M B then "L" else
      "S" ++ tree d (quad B 0) ++ tree d (quad B 1) ++ tree d (quad B 2) ++ tree d (quad B 3)
#eval (List.range NF).map fun f => (List.range NM).map fun m => tree DEPTH (cell II JJ f m)
'''

HEAD = '''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

{imports}

/-! # {title}

Generated by `scripts/qa2r_wide/emit_region_rows.py`.
-/

@[expose] public section
namespace PlasmaLean.Design.DommaschkRegionGrid
open DommaschkRegionEnclosure

'''


def scan_one(i, j):
    text = (SCAN.replace("NF", str(NF)).replace("NM", str(NM)).replace("DEPTH", str(DEPTH))
            .replace("II", str(i)).replace("JJ", str(j)))
    with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False) as handle:
        handle.write(text)
    out = subprocess.run(["lake", "env", "lean", handle.name], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout
    Path(handle.name).unlink()
    trees = re.findall(r'"([LSF]+)"', out)
    if len(trees) != NF * NM:
        raise ValueError(f"scan {i} {j}: unexpected output\n{out}")
    return {f"{i} {j} {k // NM} {k % NM}": t for k, t in enumerate(trees)}


def scan():
    trees = {}
    with ThreadPoolExecutor(max_workers=8) as pool:
        for part in pool.map(lambda ij: scan_one(*ij), [(i, j) for i in range(NI) for j in range(NJ)]):
            trees.update(part)
    return trees


def parse(tree, pos=0, path=()):
    """Return (term structure, next position); a structure is a path (leaf) or four structures."""
    if tree[pos] == "L":
        return path, pos + 1
    if tree[pos] != "S":
        raise ValueError("the check fails at the maximal depth")
    pos += 1
    children = []
    for q in range(4):
        child, pos = parse(tree, pos, path + (q,))
        children.append(child)
    return children, pos


def box(cell, path):
    expr = "cell " + cell
    for q in path:
        expr = f"quad ({expr}) {q}"
    return expr


def emit_cell(cell, tree, counter):
    structure, end = parse(tree)
    if end != len(tree):
        raise ValueError(f"malformed tree for cell {cell}")
    lines = []

    def term(node):
        if isinstance(node, tuple):
            name = f"leaf{counter[0]}"
            counter[0] += 1
            lines.append(f"private theorem {name} : good b₀ c₁ M ({box(cell, node)}) = true := by\n"
                         "  kernel_fact")
            return f".leaf {name}"
        return ".split " + " ".join(f"({term(child)})" for child in node)

    body = term(structure)
    name = "cell_" + cell.replace(" ", "_")
    lines.append(f"/-- Subdivision certificate of the cell `{cell}`. -/\n"
                 f"theorem {name} : Cert (cell {cell}) :=\n  {body}".replace(
                     ") (", ")\n    ("))
    return "\n".join(lines) + "\n"


def generate(trees):
    weights = sorted(trees, key=lambda c: (-trees[c].count("L"), tuple(map(int, c.split()))))
    bins = [[] for _ in range(FILES)]
    load = [0] * FILES
    for cell in weights:
        k = load.index(min(load))
        bins[k].append(cell)
        load[k] += trees[cell].count("L")
    files = {}
    for k, cells in enumerate(bins):
        counter = [0]
        text = HEAD.format(imports="public import PlasmaLean.Design.DommaschkRegionGrid",
                           title=f"Subdivision certificates of the QA2R envelope grid, part {k}")
        text += "\n".join(emit_cell(cell, trees[cell], counter)
                          for cell in sorted(cells, key=lambda c: tuple(map(int, c.split()))))
        text += "\nend PlasmaLean.Design.DommaschkRegionGrid\n"
        files[f"DommaschkRegionRows{k:02d}.lean"] = text
    imports = "\n".join(f"public import PlasmaLean.Design.DommaschkRegionRows{k:02d}"
                        for k in range(FILES))
    text = HEAD.format(imports=imports,
                       title="All subdivision certificates of the QA2R envelope grid")
    for i in range(NI):
        for j in range(NJ):
            for f in range(NF):
                names = ",\n    ".join(f"cell_{i}_{j}_{f}_{m}" for m in range(NM))
                text += (f"/-- The arcs of the family `{f}` over the cell `({i}, {j})`. -/\n"
                         f"theorem row_{i}_{j}_{f} : ∀ m < {NM}, Cert (cell {i} {j} {f} m) := by\n"
                         f"  intro m hm\n  interval_cases m\n  exacts [{names}]\n\n")
    names = ",\n    ".join(f"row_{i}_{j}_{f}" for i in range(NI) for j in range(NJ)
                           for f in range(NF))
    text += (f"/-- **Every cell of the grid has a subdivision certificate.** -/\n"
             f"theorem rows : ∀ i < {NI}, ∀ j < {NJ}, ∀ f < {NF}, ∀ m < {NM}, Cert (cell i j f m) := by\n"
             f"  intro i hi j hj f hf\n"
             f"  interval_cases i <;> interval_cases j <;> interval_cases f\n"
             f"  exacts [{names}]\n\n")
    text += "end PlasmaLean.Design.DommaschkRegionGrid\n"
    files["DommaschkRegionRowsAll.lean"] = text
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reuse", action="store_true", help="use the stored trees")
    parser.add_argument("--check", action="store_true", help="compare with the emitted files")
    args = parser.parse_args()
    if args.reuse or args.check:
        trees = json.loads(TREES.read_text())
    else:
        trees = scan()
        TREES.parent.mkdir(exist_ok=True)
        TREES.write_text(json.dumps(trees, indent=0, sort_keys=True) + "\n")
    if any("F" in t for t in trees.values()):
        raise SystemExit("the check fails at the maximal depth on some cell")
    files = generate(trees)
    leaves = sum(t.count("L") for t in trees.values())
    print(f"{len(trees)} cells, {leaves} leaves, {len(files)} files")
    for name, text in files.items():
        if args.check:
            if (DESIGN / name).read_text() != text:
                raise SystemExit(f"{name} differs from regeneration")
        else:
            (DESIGN / name).write_text(text)


if __name__ == "__main__":
    main()
