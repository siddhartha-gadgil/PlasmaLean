"""Emit a backward q0 defect proof from the forward sparse certificate and the actual backward row."""
import argparse
from fractions import Fraction
from math import isqrt
from pathlib import Path

from bounce_mirror_pilot import Model, R0M, SCALE, angle_models
from emit_sparse_reference_defect import HEADER
from emit_sparse_taylor_slab import DEST, RECORD, model_literal
from emit_sparse_trace_defect_samples import matrix_literal
from screen_reflected_reference import paired_jobs
from screen_sparse_reference_defects import evaluate, jobs


def render(path, index, forward_package):
    # paired_jobs checks the two central coordinates and both complete matrices.
    f,back_budget = list(paired_jobs(path))[index]
    back, = (j for j in jobs(path,8,False) if (j[1],j[2]) == (-1,index))
    r,z = (Model(v) for v in back[3])
    waves = angle_models(Fraction(-2*index-1,128),Fraction(-1,128),Fraction(0))
    coords = ',\n  '.join(map(model_literal,[r-R0M,z,waves[2],waves[1]]))
    _,_,square,_ = evaluate(f)
    sharp = isqrt((square*SCALE*SCALE).numerator // (square*SCALE*SCALE).denominator)+1
    if Fraction(sharp,SCALE) > back_budget:
        raise ArithmeticError('sharp forward bound exceeds the backward budget')
    bname = f'DommaschkReflectedBack{index:03}'
    fname = f'DommaschkTraceResidualForward{index:03}'
    block,j = divmod(index,8)
    size = min(8,391-block*8)
    offset = 2*index+1
    return HEADER + f'''public import PlasmaLean.Design.DommaschkSectionReflection
public import {forward_package}.{fname}

/-! # Physical backward defect from section-zero reflection at slab {index}

The forward component bounds are retested against a sharp bound; this bound is
compared to the distinct backward budget. Generated by
`scripts/dommaschk_kam/emit_reflected_reference.py`.
-/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{bname}
open Certificates.QPoly Certificates.TrajectoryTaylorModel
open DommaschkKam DommaschkBounceField DommaschkBounceTaylor FramedTaylorResidual
open DommaschkSectionReflection Certificates.TrajectoryHarmonicPacket
set_option linter.style.longLine false
set_option Elab.async false

/-- Actual backward central position and directed harmonic data. -/
def backReference : Inputs := ⟨{coords}⟩

/-- Actual backward frame, specified by both archived endpoint matrices. -/
def backFrame : Frame := Frame.ofEndpoints
  ({matrix_literal(back[4])})
  ({matrix_literal(back[5])})

/-- The Euclidean upper bound obtained from the checked forward component enclosures. -/
def sharp : ℚ := {sharp}/2^80

/-- This backward row's submitted defect budget. -/
def backBudget : ℚ := {back_budget}

open {fname}

/-- The actual central curves and frame endpoints obey the reflection identities. -/
theorem exact_pair : CurvePair reference backReference ∧ FramePair frame backFrame := by
  constructor <;> constructor <;> apply eq_of_beq <;> kernel_fact

private theorem actual_input {{t : ℝ}} (ht : t ∈ Set.Icc ({index} / 64 : ℝ) ({index+1} / 64)) :
    let s := 128*t-{offset}
    0 < position reference s 0 ∧ reference.Mem s (position reference s 0 - dkR0)
      (position reference s 1) (Real.cos (2*t)) (Real.sin (2*t)) := by
  let s := 128*t-{offset}
  have hs : |s| ≤ 1 := abs_le.mpr ⟨by dsimp [s]; linarith [ht.1], by dsimp [s]; linarith [ht.2]⟩
  have coords (m : Model) (h : m.radius = 0) : m.Mem s (eval m.poly s) := by simp [Model.Mem,h]
  have hu : reference.u.Mem s (position reference s 0 - dkR0) := by
    simpa only [position, Matrix.cons_val_zero, add_sub_cancel_left] using
      coords reference.u (eq_of_beq (by kernel_fact))
  have hz : reference.z.Mem s (position reference s 1) := coords reference.z (eq_of_beq (by kernel_fact))
  have hr := enclose (c := ⟨[0],1/2⟩) hs hu (by kernel_fact)
  have pos : 0 < position reference s 0 := by norm_num [Model.Mem,dkR0,abs_le] at hr; linarith
  let packet := DommaschkHarmonicBlock{block:02}.packet ({j} : Fin {size})
  have ht' : t ∈ Set.Icc ((↑({8*block}+({j} : Fin {size}).val : ℕ) : ℝ)/64)
      (((↑({8*block}+({j} : Fin {size}).val : ℕ) : ℝ)+1)/64) := by norm_num at ht ⊢; exact ht
  have cos := Certificates.TrajectoryHarmonicPacket.physical packet false 0 false ht'
  have sin := Certificates.TrajectoryHarmonicPacket.physical packet false 0 true ht'
  refine ⟨pos,hu,hz,?_,?_⟩
  · change ((packet false 0).model false).Mem _ _
    norm_num [Certificates.TrajectoryTrig.wave,s] at cos ⊢
    exact cos
  · change ((packet false 0).model true).Mem _ _
    norm_num [Certificates.TrajectoryTrig.wave,s] at sin ⊢
    exact sin

/-- Actual physical forward defect under the sharper reusable bound. -/
theorem forward_sharp {{t : ℝ}} (ht : t ∈ Set.Icc ({index} / 64 : ℝ) ({index+1} / 64)) :
    let s := 128*t-{offset}
    let v := physicalFlow 0 1 t (position reference s) - velocity reference 128 s
    let w := pulled frame s v
    Real.sqrt ((w 0)^2+(w 1)^2) ≤ (sharp:ℝ) := by
  let s := 128*t-{offset}
  have hs : |s| ≤ 1 := abs_le.mpr ⟨by dsimp [s]; linarith [ht.1], by dsimp [s]; linarith [ht.2]⟩
  have h := retest accepted (new := sharp) (by kernel_fact) (by kernel_fact)
  have built : build ⟨7,80⟩ false 128 frame reference.u reference.z dnR0 dnZ0 dD0 = ratio := by
    apply Quotient.mk.injEq .. |>.mpr
    refine ⟨Matches.eq ?_,Matches.eq ?_,Matches.eq ?_⟩ <;>
      constructor <;> apply eq_of_beq <;> kernel_fact
  rw [← built] at h
  obtain ⟨pos,arg⟩ := actual_input ht
  have args : reference.Mem s (position reference s 0 - dkR0) (position reference s 1)
      (Real.cos (2*(0 + sign false*t))) (Real.sin (2*(0 + sign false*t))) := by simpa [sign] using arg
  exact physical h dnR_checked dnZ_checked dD_checked t 0 s hs pos args
    ⟨by kernel_fact,by kernel_fact,by kernel_fact,by kernel_fact⟩

/-- Backward physical defect for this archived curve and frame satisfies its own budget. -/
theorem physical_defect {{t : ℝ}} (ht : t ∈ Set.Icc ({index} / 64 : ℝ) ({index+1} / 64)) :
    let s := 128*t-{offset}
    let v := physicalFlow 0 (-1) t (position backReference s) - velocity backReference 128 s
    let w := pulled backFrame s v
    Real.sqrt ((w 0)^2+(w 1)^2) ≤ (backBudget:ℝ) := by
  have eq := defect_eq exact_pair.1 exact_pair.2 t 128 (128*t-{offset}) (actual_input ht).1
  dsimp only at eq ⊢
  rw [eq]
  exact (forward_sharp ht).trans (by exact_mod_cast (show sharp ≤ backBudget by kernel_fact))

end PlasmaLean.Design.{bname}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--record',type=Path,default=RECORD)
    parser.add_argument('--index',type=int,choices=range(391),default=1,metavar='0..390')
    parser.add_argument('--forward-package',default='PlasmaLean.Design')
    parser.add_argument('--output',type=Path)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    path = args.output or DEST/f'DommaschkReflectedBack{args.index:03}.lean'
    out = render(args.record,args.index,args.forward_package)
    if args.check:
        if path.read_text() != out:
            raise SystemExit(f'regenerate {path}')
    else:
        path.write_text(out)
