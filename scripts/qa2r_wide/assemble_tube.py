"""Tube label hypotheses for a prefix of the wide-tube forward chain (N-216 stage 2b).

Writes `generated/qa2r_wide/WideTube/<Group>Tube.lean` for the first `8 * chunks` slabs: the
backward radii (from `tube_radii.py`), the three kernel checks, the one-sided tube structure and
its reflection to a two-sided `FlowLabel.Tube` around toroidal angle 0, with the speed bound on
the cylindrical envelope as a hypothesis.

    .venv-ws/bin/python scripts/qa2r_wide/assemble_tube.py --chunks 28
"""
import argparse
from fractions import Fraction
from pathlib import Path

import tube_radii

ROOT = Path(__file__).resolve().parents[2]


def up(x, digits=4):
    scaled = x * 10 ** digits
    return Fraction(-(-scaled.numerator // scaled.denominator), 10 ** digits)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", default="DommaschkWideTubeRows000")
    parser.add_argument("--chunks", type=int, default=28)
    args = parser.parse_args()
    group, j, n = args.group, args.chunks - 1, 8 * args.chunks
    rows = tube_radii.records(group)
    beta = tube_radii.radii(rows, n)
    expo = up(sum(max(Fraction(0), r["mu"]) / 64 for r in rows[:n]))
    binv = up(max(r["op"] / r["det"] for r in rows[:n]), 3)
    joined = group + "Joined"
    text = f"""/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import WideTube.{group}Lower
public import PlasmaLean.Certificates.PositionFrameHalfTube
public import PlasmaLean.Design.DommaschkTubeCheck
public import PlasmaLean.Design.DommaschkTubeSymmetry

/-! # The tube around forward slabs 0–{n - 1} of the wide trace and its mirror image

Generated by `scripts/qa2r_wide/assemble_tube.py`. The speed bound of the planar field-line
equation on the cylindrical envelope is a hypothesis of `halfTube` and `tube`. -/

@[expose] public section
noncomputable section
namespace PlasmaLean.Design.{group}Tube

open Certificates PositionFrameSlabs PositionFrameTube DommaschkJacobian DommaschkTubeCheck
open DommaschkTubeSymmetry DommaschkSignedTraceDomain Fields Set

set_option linter.style.longLine false
set_option maxRecDepth 100000

/-- The first {n} records of the chain. -/
abbrev rows : List Step := {joined}.all{j}

theorem length : rows.length = {n} := {joined}.length{j}

/-- Backward radii in units of 2⁻⁸⁰, from the section to the end of slab {n - 1}. -/
def beta : List ℕ := [{', '.join(map(str, beta))}]

/-- Radius of the inner tube at the end of slab `k - 1`. -/
def β (k : ℕ) : ℝ := (beta.getD k 0 : ℝ) / 2 ^ 80

theorem radii_checked : radiiCheck rows beta = true := by with_unfolding_all rfl

theorem envelope_checked : rows.all trialPacked = true := by with_unfolding_all rfl

/-- Exponent of the backward growth and bound for the inverse frames. -/
def exponent : ℚ := {expo}

def inverseBound : ℚ := {binv}

theorem constants_checked : constCheck rows exponent inverseBound = true := by
  with_unfolding_all rfl

theorem geo : Geo {group}.start rows := Geo.of_steps {joined}.stepsTo{j}

private theorem zero : (0 / 64 : ℝ) = 0 := zero_div _

theorem bounds : FieldBoundsOn (euclideanFlow 0 1) (velocityJacobian 0 1) {group}.start 0 rows
    ballDomain := by
  have h := {joined}.boundsTo{j}
  rwa [zero] at h

theorem lower : LowerOn (velocityJacobian 0 1) {group}.start 0 rows := by
  have h := {group}Lower.lowerTo{j}
  rwa [zero] at h

theorem positive : 0 < rows.length := by rw [length]; norm_num

/-- End of the tube: toroidal angle {n}/64. -/
theorem stop : time 0 rows.length = {n} / 64 := by
  rw [length]
  norm_num [time, PiecewiseTube.node]

/-- Lipschitz constant of the section label in the plane. -/
def labelConstant : ℝ := 1 * Real.exp exponent * inverseBound

theorem one_le_labelConstant : 1 ≤ labelConstant := by
  have h : (1 : ℝ) ≤ Real.exp (exponent : ℚ) := Real.one_le_exp (by norm_num [exponent])
  have b : (1 : ℝ) ≤ (inverseBound : ℚ) := by norm_num [inverseBound]
  unfold labelConstant
  nlinarith

/-- Every point of the trial tube lies in the cylindrical envelope. -/
theorem region_of_outer {{t : ℝ}} {{x : Plane}} (hx : x ∈ outer {group}.start 0 rows t) :
    Region x := DommaschkTubeCheck.region_of_outer geo envelope_checked hx

/-- **One-sided tube.** For toroidal angles in `[0, {n}/64)`: from the inner tube field lines
run back to angle 0 inside the trial tube, where they are unique and at most `labelConstant`
times further apart at angle 0. -/
theorem halfTube {{M : ℝ}} (hM : 0 ≤ M)
    (speed : ∀ (t : ℝ) (x : Plane), Region x → ‖euclideanFlow 0 1 t x‖ ≤ M) :
    FlowLabel.HalfTube (euclideanFlow 0 1) flipIso 0 (time 0 rows.length)
      (outer {group}.start 0 rows) (inner {group}.start 0 rows β) labelConstant M := by
  obtain ⟨hE, hB⟩ := const_of_check constants_checked
  exact PositionFrameTube.halfTube geo bounds lower (radii_of_check radii_checked) positive hE
    (frameAt_start_identity geo positive rfl) hB one_le_labelConstant hM flipIso
    flipIso_involutive (fun t x hx => speed t x (region_of_outer hx))
    (fun t x hx => flow_symm t x (by linarith [(region_of_outer hx).1.1]))

/-- **Two-sided tube** around toroidal angle 0, by the phase-zero reflection. -/
theorem tube {{M : ℝ}} (hM : 0 ≤ M)
    (speed : ∀ (t : ℝ) (x : Plane), Region x → ‖euclideanFlow 0 1 t x‖ ≤ M) :
    FlowLabel.Tube (euclideanFlow 0 1) 0 (2 * 0 - time 0 rows.length) (time 0 rows.length)
      (FlowLabel.doubleW flipIso 0 (outer {group}.start 0 rows))
      (FlowLabel.doubleV flipIso 0 (inner {group}.start 0 rows β)) labelConstant M :=
  (halfTube hM speed).double

/-- The space-time region over the two-sided inner tube is open. -/
theorem isOpen_region : IsOpen (FlowLabel.region (2 * 0 - time 0 rows.length)
    (time 0 rows.length) (FlowLabel.doubleV flipIso 0 (inner {group}.start 0 rows β))) :=
  PositionFrameTube.isOpen_region geo (radii_of_check radii_checked) flipIso flipIso_involutive
    positive

end PlasmaLean.Design.{group}Tube
"""
    path = ROOT / "generated/qa2r_wide/WideTube" / (group + "Tube.lean")
    path.write_text(text)
    print(path, "slabs", n, "exponent", expo, "inverse", binv)


if __name__ == "__main__":
    main()
