"""Build the eight coarse action packets and audit their strict endpoint comparisons."""
import argparse
from concurrent.futures import ThreadPoolExecutor
from fractions import Fraction as F
import os
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
from types import SimpleNamespace

from emit_action_quadrature import write_table
from screen_action_panel_resolution import screen
from verify_backward_physical_prefix import compile_modules
from verify_common_endpoint_traces import ENDPOINTS
from verify_physical_trace_slabs import ROOT, digest, save


PACKAGE = 'CoarseActionPacketCache'


def check(endpoint, args, version):
    m = 16 if endpoint in ('q0r478','q0r531') else 12
    groups = {m:([],[])}
    known = screen(endpoint,[m],groups=groups)
    sums = known['coarse'][m]
    if not sums['accepted']:
        raise ValueError(f'coarse physical enclosures miss the required action target at {endpoint}')
    name = f'DommaschkCoarseAction{endpoint.upper()}N{m}'
    with TemporaryDirectory() as scratch:
        path = Path(scratch)
        write_table(groups[m], F(known['height']), known['upper'], name,
                    f"{endpoint}, {m} independent physical enclosures per slab", path, splits=m)
        source = (path/(name+'.lean')).read_text().replace(
            'Generated by `scripts/dommaschk_kam/emit_action_quadrature.py`.',
            'Generated by `scripts/dommaschk_kam/verify_coarse_action_packets.py`.')
    parent = ROOT/'.lake/build/lib/lean/PlasmaLean/Certificates/MirrorActionQuadrature.trace'
    keys = [version,digest(parent),known['packet_sha256'],known['action_sha256']]
    declaration = (name,source,['endpoint'])
    root,record = compile_modules(args.cache/name,[declaration],[],keys,args,PACKAGE)
    arithmetic = f'PlasmaLean.Design.{name}.checked'
    with TemporaryDirectory() as scratch:
        audit = Path(scratch)/'PacketArithmetic.lean'
        audit.write_text(f'import {PACKAGE}.{name}\n#print axioms {arithmetic}\n')
        env = {**os.environ,'LEAN_PATH':os.pathsep.join([str(root),args.lean_path]),'LEAN_NUM_THREADS':'1'}
        actual = subprocess.check_output([args.lean,'-j1','-DwarningAsError=true',str(audit)],
                                         cwd=ROOT,env=env,text=True).strip()
        if actual != f"'{arithmetic}' depends on axioms: [propext]":
            raise ValueError(f'unexpected axioms for the finite packet: {actual}')
    out = {k:v for k,v in record.items() if k != 'artifacts'}
    out.update(endpoint=endpoint, package=PACKAGE, splits=m, upper=known['upper'],
               height=known['height'], target=known['target'], counts=known['counts'],
               packet_sha256=known['packet_sha256'], action_sha256=known['action_sha256'],
               mass=sums['action'], margin=sums['margin'], panels=sums['panels'], import_paths=[str(root)],
               arithmetic_theorem=arithmetic, arithmetic_axioms=['propext'])
    save(args.output_dir/(endpoint+'.json'),out)
    print(endpoint,record['key'],flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--endpoints',nargs='+',choices=ENDPOINTS,default=ENDPOINTS)
    parser.add_argument('--workers',choices=(1,2),type=int,default=1)
    parser.add_argument('--output-dir',type=Path,required=True)
    parser.add_argument('--cache',type=Path,default=ROOT/'.lake/coarse-action-packets')
    options = parser.parse_args()
    if len(set(options.endpoints)) != len(options.endpoints):
        parser.error('repeat endpoints are not valid')
    def lake(*cmd):
        return subprocess.check_output(['lake','env',*cmd],cwd=ROOT,text=True).strip()
    args = SimpleNamespace(lean=str(Path(lake('lean','--print-prefix'))/'bin/lean'),
                           lean_path=lake('printenv','LEAN_PATH'),cache=options.cache.resolve(),
                           output_dir=options.output_dir.resolve())
    args.output_dir.mkdir(parents=True,exist_ok=True)
    version = lake('lean','--version')
    with ThreadPoolExecutor(max_workers=options.workers) as pool:
        list(pool.map(lambda endpoint: check(endpoint,args,version),options.endpoints))


if __name__ == '__main__':
    main()
