"""Emit checked powers shared by all sparse fields and derivatives of one input tube."""
from bounce_mirror_pilot import ONE
from emit_sparse_taylor_slab import DATA, coefficients, model_literal


def add_shared_powers(modules, inputs_module, namespace, columns, value='trial'):
    """Replace each original block constructor by the proved table-lookup constructor."""
    source = DATA.read_text()
    terms = sum([coefficients(source,p) for p in ('dD','dnR','dnZ')],[])
    values = []
    lengths = []
    for axis,column in enumerate(columns):
        powers = [ONE]
        for _ in range(max(e[axis] for _,e in terms)):
            powers.append(powers[-1]*column)
        values.append('['+',\n  '.join(map(model_literal,powers))+']')
        lengths.append(len(powers))

    name = namespace+'Stored'
    text = f'''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Design.DommaschkStoredPowers
public import PlasmaLean.Design.{inputs_module}

/-! # Shared powers of the radial, vertical, cosine, and sine Taylor models

Generated by `scripts/dommaschk_kam/shared_sparse_powers.py`. -/

@[expose] public section
namespace PlasmaLean.Design.{namespace}
open DommaschkStoredPowers DommaschkBounceTaylor Certificates.TrajectoryTaylorModel

set_option linter.style.longLine false
set_option Elab.async false
set_option maxRecDepth 16000

def storedPowers : Powers := ⟨''' + ',\n  '.join(values) + '⟩\n\n'
    text += f'theorem storedPowers_checked : storedPowers.Checked ⟨7, 80⟩ {value} := by\n  constructor\n'
    for length in lengths:
        proof = 'Valid.nil _'
        for _ in range(length):
            proof = 'Valid.cons ?_ ('+proof+')'
        text += '  · refine '+proof+'\n    all_goals constructor <;> apply eq_of_beq <;> kernel_fact\n'
    text += '\nend PlasmaLean.Design.'+namespace+'\n'

    result = {}
    for key,body in modules.items():
        if 'apply Blocks.chunk ' in body:
            body = body.replace('public import PlasmaLean.Design.'+inputs_module+'\n',
                                'public import PlasmaLean.Design.'+name+'\n')
            body = body.replace('apply Blocks.chunk ',
                                'apply DommaschkStoredPowers.checkedChunk storedPowers storedPowers_checked ')
        result[key] = body
        if key == inputs_module:
            result[name] = text
    return result
