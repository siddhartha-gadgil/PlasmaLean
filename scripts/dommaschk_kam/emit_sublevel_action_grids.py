"""Emit the eight adaptive sublevel-action grids at their archived heights and targets."""
import argparse
from fractions import Fraction
import re

from screen_sublevel_speed_grid import (
    DENOMINATOR, DESIGN, MAX_SPEED, SCALE, adaptive_table, extract,
)


def endpoint(path):
    upper, target, weights = extract(path)
    cells, mass, margin = adaptive_table(weights, upper, target)
    side = str(upper).lower()
    height, = re.findall(r'\(phys : Covers '+side+r' w f \((\d+) / (\d+) : ℝ\)', path.read_text())
    h = Fraction(int(height[0]), int(height[1]))
    if not (h <= 2 and sum(width for width, _ in cells) == MAX_SPEED
            and all(width > 0 for width, _ in cells) and margin > 0):
        raise ValueError(f'{path.name}: invalid grid or height')
    name = path.stem.removeprefix('DommaschkAction')
    rows = ',\n  '.join(f'⟨{width}, {tail}⟩' for width, tail in cells)
    density_scale = DENOMINATOR // SCALE
    assert SCALE * density_scale == DENOMINATOR
    action = 'action μ B mirrorHeight'
    target_real = f'({target.numerator} / {target.denominator} : ℝ)'
    goal = f'{action} < {target_real}' if upper else f'{target_real} < {action}'
    mass_term = f'mass table * {target.denominator}'
    target_term = f'{target.numerator} * ({SCALE} * {density_scale})'
    comparison = f'{mass_term} < {target_term}' if upper else f'{target_term} < {mass_term}'
    return f'''namespace {name}

/-- Archived mirror height used for this endpoint. -/
noncomputable def mirrorHeight : ℝ := {h.numerator} / {h.denominator}

/-- Adaptive cell widths and directed sublevel arclength heights in integer ticks. -/
def table : Table := #[
  {rows}]

theorem panel_count : table.size = {len(cells)} := rfl

theorem positive_widths {{i : ℕ}} (hi : i < table.size) : 0 < (cell table i).width :=
  widths_positive (by rfl) hi

theorem exact_mass : mass table = {mass} := by rfl

theorem checked : Certified table {SCALE} {density_scale} {side}
    {target.numerator} {target.denominator} := by
  constructor
  · norm_num
  · norm_num
  · norm_num
  · rfl
  · change {comparison}
    rw [exact_mass]
    norm_num

/-- Strict target for any finite measured well satisfying these directed node bounds. -/
theorem endpoint {{X : Type*}} [MeasurableSpace X] (μ : Measure X) [IsFiniteMeasure μ]
    {{B : X → ℝ}} (hB : AEMeasurable B μ) (nonneg : ∀ᵐ x ∂μ, 0 ≤ B x)
    (nodes : NodeBounds μ B mirrorHeight table {SCALE} {density_scale} {side}) :
    {goal} := by
  have floorB : ∀ᵐ x ∂μ, mirrorHeight - 2 ≤ B x :=
    nonneg.mono fun _ hx => le_trans (by norm_num [mirrorHeight]) hx
  exact action_target μ hB floorB checked nodes

end {name}
'''


def generate():
    sources = sorted(DESIGN.glob('DommaschkActionQ[01]R[0-9][0-9][0-9].lean'))
    if len(sources) != 8:
        raise ValueError('expected eight directed action endpoint sources')
    return '''/-
Copyright (c) 2026 PlasmaLean contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: PlasmaLean contributors
-/
module

public import PlasmaLean.Certificates.SublevelActionGrid

/-! # Adaptive action grids at the eight Dommaschk endpoints

Generated by `scripts/dommaschk_kam/emit_sublevel_action_grids.py`. Each theorem
states as hypotheses the node arclength inequalities on the proposed physical well.
-/

@[expose] public section
namespace PlasmaLean.Design.DommaschkSublevelActionGrids

open MeasureTheory PlasmaLean.Certificates.SublevelActionGrid
open PlasmaLean.Kinetic.MirrorSublevelAction

set_option maxRecDepth 16384

''' + '\n'.join(endpoint(path) for path in sources) + '''
end PlasmaLean.Design.DommaschkSublevelActionGrids
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = DESIGN / 'DommaschkSublevelActionGrids.lean'
    output = generate()
    if args.check:
        if output != path.read_text():
            raise SystemExit('regenerate the adaptive sublevel action grids')
    else:
        path.write_text(output)
