def qlean(q):
    q = Fr(q)
    den = q.denominator
    k10, d = 0, den
    while d % 10 == 0:
        d //= 10
        k10 += 1
    if d == 1:
        return '(%d / 10 ^ %d : ℚ)' % (q.numerator, k10)
    if den & (den - 1) == 0:
        return '(%d / 2 ^ %d : ℚ)' % (q.numerator, den.bit_length() - 1)
    return '(%d / %d : ℚ)' % (q.numerator, den)


